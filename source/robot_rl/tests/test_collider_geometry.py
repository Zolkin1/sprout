"""No two of the robot's own colliders may start out inside each other.

Self-collision is ON, and PhysX only auto-filters ADJACENT links. Two bodies further apart
in the tree that overlap at the rest pose cannot be resolved by moving apart when a FIXED
joint welds them together, so the solver simply pushes -- forever, from the first step, with
no contact event anyone would look at.

That is not hypothetical. Giving the compute backpack a collider sized to its own mesh put
it 2.09 mm into the torso box across a 180 x 190 mm face. The robot then drifted +0.38 m
FORWARD during one second of settling, when its own added mass should have carried it
backwards -- and it did drift -0.19 m backwards in the same test before the collider
existed. Nothing failed, nothing warned; the number was just wrong.

Only the REST pose is checked, because that is the configuration every episode starts in and
the one a static overlap shows up in. A pair that can be driven into contact by moving a
joint is a different question -- that is what self-collision is FOR, and the answer there is
a real contact, not a modelling error.
"""

from __future__ import annotations

import os
import pathlib
import xml.etree.ElementTree as ET
from functools import partial

import numpy as np
import pytest

yourdfpy = pytest.importorskip("yourdfpy", reason="URDF parsing")

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
URDF_PATH = _REPO_ROOT / "robot_assets" / "g1_perceptive" / "g1_perceptive.urdf"

#: Clearance a pair must keep at the rest pose, in metres. Not zero: a pair that merely
#: touches is one solver tolerance away from the failure above, and the meshes these boxes
#: stand for are known only to a few millimetres anyway.
MIN_CLEARANCE_M = 0.002


def _boxes() -> dict[str, tuple[np.ndarray, np.ndarray]]:
    """Every box collider as ``(centre, half_extents)`` in the pelvis frame at zero joints.

    Boxes only, deliberately: they are what this robot's colliders are (the foot boxes, the
    torso box, the backpack), and an AABB test on them is exact rather than approximate.

    Returns:
        Link name -> ``(centre, half_extents)``.
    """
    urdf = yourdfpy.URDF.load(
        str(URDF_PATH), build_scene_graph=True, load_meshes=False,
        filename_handler=partial(yourdfpy.filename_handler_magic,
                                 dir=os.path.dirname(URDF_PATH)),
    )
    out: dict[str, tuple[np.ndarray, np.ndarray]] = {}
    for link in ET.parse(URDF_PATH).getroot().findall("link"):
        for collision in link.findall("collision"):
            box = collision.find("geometry/box")
            if box is None:
                continue
            origin = collision.find("origin")
            local = np.array([float(v) for v in
                              (origin.get("xyz", "0 0 0") if origin is not None
                               else "0 0 0").split()])
            transform = urdf.get_transform(link.get("name"), "pelvis_link")
            centre = transform[:3, :3] @ local + transform[:3, 3]
            half = np.array([float(v) for v in box.get("size").split()]) / 2.0
            out[link.get("name")] = (centre, half)
    return out


def _links_with_any_collider() -> set[str]:
    """Links carrying at least one ``<collision>``, whatever its geometry.

    Separate from :func:`_boxes` on purpose: the overlap test is box-only because an AABB
    test on boxes is EXACT, while "can this body report contact at all" does not care what
    shape the collider is. Conflating the two claimed the knees had no collider, when what
    they have is simply not a box.
    """
    return {link.get("name") for link in ET.parse(URDF_PATH).getroot().findall("link")
            if link.findall("collision")}


@pytest.fixture(scope="module")
def any_collider() -> set[str]:
    """Every link with a collider of any shape."""
    return _links_with_any_collider()


@pytest.fixture(scope="module")
def boxes():
    """The robot's box colliders, in the pelvis frame."""
    if not URDF_PATH.is_file():
        pytest.fail(
            f"{URDF_PATH} is missing -- it is generated by "
            "robot_assets/g1_perceptive/make_perceptive_urdf.py"
        )
    found = _boxes()
    assert found, "no box colliders found at all; the URDF or this parser is wrong"
    return found


def test_colliders_do_not_interpenetrate(boxes):
    """Every pair of box colliders is clear of every other at the rest pose."""
    names = sorted(boxes)
    bad = []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            (ca, ha), (cb, hb) = boxes[a], boxes[b]
            # Per-axis separation; a pair is clear if ANY axis separates them.
            gap = np.abs(ca - cb) - (ha + hb)
            if gap.max() < MIN_CLEARANCE_M:
                bad.append((a, b, float(gap.max())))
    assert not bad, "\n".join(
        f"{a} and {b} are only {g * 1000:+.2f} mm apart at the rest pose "
        f"(need {MIN_CLEARANCE_M * 1000:.0f} mm)" for a, b, g in bad
    )


#: The contact sensors in ``g1_clf_tracking_base.ClfTrackingBaseEnvSceneCfg``, and whether
#: each matches its link EXACTLY or matches that link's subtree with a trailing ``/.*``.
#: The distinction is the whole point: an exact match needs a collider on that very body,
#: while a subtree match is satisfied by any descendant. ``left_hip_pitch_link`` has no
#: collider of its own and ``left_thigh_contact`` is fine, because it watches the subtree.
CONTACT_SENSORS: tuple[tuple[str, str, bool], ...] = (
    ("left_thigh_contact", "left_hip_pitch_link", True),
    ("right_thigh_contact", "right_hip_pitch_link", True),
    ("torso_contact", "torso_link", False),
    ("backpack_contact", "backpack_shell_link", False),
    ("left_elbow_contact", "left_shoulder_yaw_link", True),
    ("right_elbow_contact", "right_shoulder_yaw_link", True),
    ("left_foot_contact", "left_ankle_pitch_link", True),
    ("right_foot_contact", "right_ankle_pitch_link", True),
    ("left_shin_contact", "left_knee_link", False),
    ("right_shin_contact", "right_knee_link", False),
)


def _descendants(link: str) -> set[str]:
    """``link`` and everything below it in the URDF's joint tree."""
    root = ET.parse(URDF_PATH).getroot()
    children: dict[str, list[str]] = {}
    for joint in root.findall("joint"):
        children.setdefault(joint.find("parent").get("link"), []).append(
            joint.find("child").get("link"))
    out, stack = set(), [link]
    while stack:
        cur = stack.pop()
        if cur in out:
            continue
        out.add(cur)
        stack.extend(children.get(cur, []))
    return out


@pytest.mark.parametrize("sensor,link,subtree", CONTACT_SENSORS)
def test_every_contact_sensor_watches_a_body_with_a_collider(sensor, link, subtree,
                                                             any_collider):
    """A contact sensor needs something to make contact WITH.

    ``torso_contact`` was dead from the day the 29-DOF waist was un-merged until 2026-08-19:
    it names ``torso_link`` exactly, the box was on ``waist_yaw_link``, and so one of the
    five ``undesired_contacts`` sensors could never fire. Nothing said so -- a sensor
    watching a collider-less body is not an error, it is just always quiet.

    Read from the URDF rather than the env cfg so it needs no simulator. That means the
    sensor list here is a transcription, and a sensor added to the cfg without being added
    here is not covered -- worth the trade, because the alternative is importing IsaacLab
    and building a scene to ask a question the URDF already answers.
    """
    covered = _descendants(link) if subtree else {link}
    hits = covered & any_collider
    assert hits, (
        f"{sensor} watches {link}{'/.*' if subtree else ''}, and "
        f"{'nothing in that subtree has' if subtree else 'that body has no'} a collider. "
        "It will never fire, and it will never say so."
    )


def test_the_backpack_has_a_collider(boxes):
    """The pack must be able to register contact at all.

    A contact sensor on a body with no collider never fires and never says so.
    ``backpack_contact`` exists precisely because the pack is the first thing to meet a wall
    the robot backs into.
    """
    assert "backpack_shell_link" in boxes, (
        "backpack_shell_link has no box collider, so backpack_contact is a dead sensor"
    )
