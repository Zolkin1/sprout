"""The two sims must ray-cast the SAME parts of the robot.

IsaacLab casts exactly the prims in ``g1_self_scan.self_scan_prim_paths()``. MuJoCo casts
geom group 1 unconditionally (``transfer/sim/depth_camera.py``), which is every per-link
visual mesh. Nothing connects the two, and a body present in one and absent from the other
is a pixel-level difference in the exact signal the generator uses to place a reference.

That has happened. The hands were absent from the Isaac cast while MuJoCo had them, and the
two disagreed by ~60 of 780 near-camera pixels; the renderer looked correct throughout.

This test does NOT require the two sets to be equal -- they are not, and some of the
difference is deliberate. It requires the difference to be exactly
:data:`EXPECTED_MUJOCO_ONLY`, so that a change on either side has to be classified rather
than absorbed.
"""

from __future__ import annotations

import pathlib

import pytest

mujoco = pytest.importorskip("mujoco", reason="the MuJoCo model is the other half of this")

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
MJCF_PATH = _REPO_ROOT / "transfer" / "sim" / "robots" / "g1" / "g1_perceptive.xml"

#: Bodies MuJoCo ray-casts that IsaacLab does not, and why each is tolerable.
#:
#: All of them are the SPINE and its fixed decorations -- the structure the cameras are
#: bolted to. IsaacLab leaves them out because a camera cannot usefully occlude itself
#: (``g1_self_scan.UNSCANNED_LINKS``); MuJoCo includes them because group 1 is every visual
#: mesh and there is no per-body switch short of moving the geom to another group, which is
#: what the camera mounts get.
#:
#: This is a KNOWN GAP carried forward, not a claim that it does not matter. The torso in
#: particular is plausibly in frame at the bottom of the near camera's 100 deg cone, and
#: ``scripts/rsl_rl/compare_depth_sim2sim.py`` is the tool that would show it. Pinned here so
#: the list cannot grow quietly.
EXPECTED_MUJOCO_ONLY: frozenset[str] = frozenset({
    "pelvis_link",          # cast by Isaac too, but via root_visual_prim_paths, not this list
    "waist_yaw_link",
    "waist_roll_link",
    "torso_link",
})
#: NOTE: head_link, logo_link, waist_support_link and pelvis_contour_link are NOT in that
#: list, though they are visible in both sims. They are fixed-joint children that the merge
#: folded into their parents, so their meshes are geoms ON torso_link / pelvis_link rather
#: than bodies of their own. Naming them here would fail for a body that does not exist.


@pytest.fixture(scope="module")
def mujoco_raycast_bodies() -> set[str]:
    """Bodies with at least one geom in group 1 -- what MuJoCo's depth cameras hit."""
    if not MJCF_PATH.is_file():
        pytest.fail(
            f"{MJCF_PATH} is missing. It is generated by "
            "transfer/sim/robots/g1/make_g1_mjcf.py; skipping would report success for a "
            "cross-sim check that never ran."
        )
    model = mujoco.MjModel.from_xml_path(str(MJCF_PATH))
    out = set()
    for i in range(model.ngeom):
        if int(model.geom_group[i]) != 1:
            continue
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, model.geom_bodyid[i])
        if name:
            out.add(name)
    return out


@pytest.fixture(scope="module")
def isaac_scan_links() -> set[str]:
    """What IsaacLab casts, from the self-scan config."""
    from robot_rl.tasks.manager_based.robot_rl.g1 import g1_self_scan as ss
    return set(ss.SELF_SCAN_LINKS)


def test_isaac_casts_nothing_mujoco_misses(isaac_scan_links, mujoco_raycast_bodies):
    """Every body IsaacLab ray-casts is also in MuJoCo's group 1.

    This direction has no acceptable exceptions. A body Isaac sees and MuJoCo does not means
    sim2sim is missing an occluder the policy was trained against, which shows up as depth
    that is too FAR -- the failure mode that reads as terrain, not as a bug.
    """
    missing = isaac_scan_links - mujoco_raycast_bodies
    assert not missing, (
        f"{sorted(missing)} are ray-cast in IsaacLab but not in MuJoCo. Check the geom group "
        "in the generated MJCF (make_g1_mjcf.NO_RAYCAST_BODIES moves things out of group 1)."
    )


def test_the_mujoco_only_bodies_are_the_expected_ones(isaac_scan_links,
                                                      mujoco_raycast_bodies):
    """The other direction is allowed, but only for a fixed, explained list."""
    extra = mujoco_raycast_bodies - isaac_scan_links
    assert extra == EXPECTED_MUJOCO_ONLY, (
        f"MuJoCo-only ray-cast bodies changed.\n"
        f"  newly MuJoCo-only: {sorted(extra - EXPECTED_MUJOCO_ONLY)}\n"
        f"  no longer:         {sorted(EXPECTED_MUJOCO_ONLY - extra)}\n"
        "Classify the change: add it to g1_self_scan.SELF_SCAN_LINKS so both sims cast it, "
        "move its geom out of group 1 in make_g1_mjcf.NO_RAYCAST_BODIES so neither does, or "
        "record it here with the reason."
    )


def test_the_camera_mounts_are_cast_by_neither(isaac_scan_links, mujoco_raycast_bodies):
    """The mounts are excluded on BOTH sides, which is the point of excluding them at all.

    A camera has no use for a picture of its own housing, and these are the heaviest meshes
    on the robot. Excluding them in one sim only would just move the cost into a divergence.
    """
    for mount in ("camera_lower_mount_link", "camera_upper_mount_link"):
        assert mount not in isaac_scan_links, f"{mount} is ray-cast in IsaacLab"
        assert mount not in mujoco_raycast_bodies, f"{mount} is in MuJoCo's group 1"
