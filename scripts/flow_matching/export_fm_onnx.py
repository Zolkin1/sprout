class _FmSamplerOnnx(nn.Module):
    """ONNX-exportable wrapper: raw inputs -> denormalized relative-state future window.

    Folds the history/height/command normalization and the target denormalization
    into the graph, and unrolls the ``num_steps`` Euler integration of the learned
    flow. The history/height/command are separate conditioning tokens (held fixed
    across integration); the F future tokens are the only denoised ones -- there is
    no inpainting / known mask / re-clamp.
    """

    def __init__(self, ctx: FmOnlineContext, advantage_label: int | None = None):
        """Capture the model + normalizer statistics as buffers from a loaded context.

        Args:
            ctx: The loaded context.
            advantage_label: For an advantage-conditioned checkpoint, the label to BAKE IN
                as a constant. It is a constant at inference (the deployment always asks for
                one arm), so it never becomes a graph INPUT: ``_IO_NAMES``, ``fm_session``
                on both sides, the C++ ``bound_inputs_`` and the CUDA-graph binding are all
                untouched, and the negative control is simply a second graph. ``None`` for an
                unconditioned checkpoint.
        """
        super().__init__()
        self.model = ctx.model
        self.num_steps = int(ctx.num_steps)
        self.advantage_label = (None if advantage_label is None else int(advantage_label))
        if self.advantage_label is not None:
            # A shape-(1,) CONSTANT, not a batch-derived tensor. `nn.Embedding` returns
            # (1, d_model), which broadcasts against the (B, d_model) flow-time embedding, so
            # one constant serves any batch -- and being a constant it folds into an
            # initializer instead of becoming int64 arithmetic on an input. That matters
            # beyond tidiness: onnxruntime keeps int64 work on the HOST, and a single host
            # node makes the whole graph ineligible for CUDA Graph capture (it refuses to
            # create the session at all), which is where 8.3 of the 14-15 ms Thor budget
            # comes from.
            self.register_buffer(
                "advantage_idx",
                torch.tensor([self.advantage_label], dtype=torch.long), persistent=False)
        # Plain ints/tuples, so the SO(3) projection below traces as fixed slicing.
        self.nj = int(ctx.nj)
        self.num_extra_frames = int(ctx.target_num_extra_frames)
        self.reference_blocks = tuple(ctx.reference_blocks)
        self.register_buffer("s_mean", ctx.state_norm.mean.detach().clone())
        self.register_buffer("s_std", ctx.state_norm.std.detach().clone())
        self.register_buffer("c_mean", ctx.cmd_norm.mean.detach().clone())
        self.register_buffer("c_std", ctx.cmd_norm.std.detach().clone())
        self.register_buffer("h_mean", ctx.extero_norm.mean.detach().clone())
        self.register_buffer("h_std", ctx.extero_norm.std.detach().clone())

    def forward(
        self,
        history: torch.Tensor,
        extero: torch.Tensor,
        cmd_tokens: torch.Tensor,
        noise: torch.Tensor,
        history_null: torch.Tensor,
    ) -> torch.Tensor:
        """Normalize the conditioning, Euler-sample the F future from ``noise``, denormalize.

        ``history_null`` is a ``(V, 1)`` float flag (>0.5 = null) rather than a bool, because a
        bool graph input is awkward across runtimes; it selects the model's learned
        ``null_history`` embedding in place of the history content. That is what lets the
        deployed generator sample before its history window has filled, matching the RL side.
        """
        hist_n = (history - self.s_mean) / self.s_std        # (V, N, D)
        height_n = (extero - self.h_mean) / self.h_std       # (V, T*extero_flat_dim)
        cmd_n = (cmd_tokens - self.c_mean) / self.c_std      # (V, n_cmd, cmd)
        null_m = (history_null.reshape(-1) > 0.5)            # (V,) bool

        x = noise                                            # (V, F, D) -- all F denoised
        dt = 1.0 / self.num_steps
        # Under ``prefix`` attention the conditioning's representation does not depend on the
        # noised tokens or on the flow time, so it is encoded ONCE rather than ``num_steps``
        # times. Held as a local, never on ``self``: this module is TorchScript-traced, and a
        # cache stashed as module state would be constant-folded into the exported weights.
        #
        # TODO(fm-onnx-prefix): this hoist makes the exported graph SLOWER at the deploy batch
        # of 1, which is the opposite of its purpose here. MEASURED on the xl27M: 13.3 ms
        # against 10.8 ms on CUDA, with 13.4k graph nodes against 10.6k. Fewer FLOPs but more
        # kernels -- one extra layer stack for the conditioning plus a Concat per layer per
        # step -- and at batch 1 onnxruntime is launch-bound, so time tracks node count. The
        # saving is real where the kernels are big: the TORCH path at Isaac's batch sizes gets
        # 1.34-1.39x on the CNN model, so this is an ORT/graph-shape problem rather than an
        # arithmetic one.
        #
        # First thing to check: ORT has a FUSED Attention kernel that pattern-matches
        # self-attention (q, k, v from ONE input). ``decode_future`` passes query=future,
        # key=value=cat(prefix, future), which plausibly breaks that match -- so ``full`` may be
        # getting a fused kernel that this path is not. Dump both graphs with
        # ``sess_options.optimized_model_filepath`` and compare their Attention nodes.
        #
        # Fallback, already scoped and proven equivalent by
        # ``test_prefix_attention_matches_a_masked_full_pass``: export ``prefix`` mode as a
        # MASKED full-sequence pass -- same semantics and same node count as ``full``, no
        # speedup but no regression -- and keep this cached form for the torch path only. Keep
        # any such mask strictly 2-D ``(S, S)``, which broadcasts; a 3-D one bakes in a static
        # batch and breaks the dynamic-batch contract the five graph inputs share.
        cache = (self.model.encode_prefix(hist_n, height_n, cmd_n, null_m)
                 if self.model.attention_mode == "prefix" else None)
        adv = None if self.advantage_label is None else self.advantage_idx
        for i in range(self.num_steps):
            # Batch-derived tau (V,) so the graph stays dynamic in the batch axis.
            tau = noise[:, 0, 0] * 0.0 + (i * dt)
            v = (self.model.decode_future(x, tau, cache, adv) if cache is not None
                 else self.model(x, tau, hist_n, height_n, cmd_n, history_null_mask=null_m,
                                 advantage=adv))
            x = x + dt * v
        # Project the rotation block back onto SO(3), exactly as
        # ``flow_matching.online.sample_window`` does for simulation -- the model emits 6
        # free numbers, and this window is both a reference pose and the next step's history
        # token. Inside the graph so the torch-free runtime needs no rotation maths.
        return project_window_rotations(
            x * self.s_std + self.s_mean,
            self.nj, self.num_extra_frames, self.reference_blocks,
        )


def _fm_meta(ctx: FmOnlineContext) -> dict:
    """Deployment metadata embedded in the ONNX (replaces the .pt config/meta)."""
    return {
        "joint_names": list(ctx.joint_names),
        "target_frame_names": list(ctx.target_frame_names),
        "N": ctx.N, "F": ctx.F, "D": ctx.D, "nj": ctx.nj, "num_steps": ctx.num_steps,
        "cmd_dim": ctx.cmd_dim, "cmd_steps": list(ctx.cmd_steps), "num_cmd_tokens": ctx.num_cmd_tokens,
        "extero_sensor_dim": int(ctx.model.extero_sensor_dim),
        # Which sensor feeds the exteroception tokens, how many there are, and -- for the
        # depth cameras -- their full contract, so the deployment feeds the right reading
        # and can verify it describes the same physical sensor as the tracker's.
        "extero_source": str(ctx.extero_source),
        "extero_sensor_count": int(ctx.model.extero_sensor_count),
        "extero_spec": ctx.extero_spec,
        # WHICH ROBOT the recording behind this generator was made with. The tracker stamps the
        # same fingerprint (export_parameters), and GenTrackerPolicy.load refuses a pair that
        # disagrees -- joint names and their order survive a payload change, a hand swap and a
        # gear-ratio change, so `joint_names_isaac` (the only field that came close) matches
        # across all of them and cannot catch this. Until this key was written the check
        # short-circuited on the absent FM side and never fired at all.
        "robot_asset": ctx.robot_asset,
        # WHICH exteroception embedding is baked into the graph, and the geometry it folds
        # the flat row with. The runtime does not need these to run -- the reshape is inside
        # the graph -- but it needs them to CHECK: ``extero_sensor_dim`` alone cannot tell a
        # 30x26 camera from a 26x30 one, and a transposed camera at deploy is a scrambled
        # image rather than a reordered vector. ``tokens_per_sensor`` is the sequence
        # arithmetic, which nothing else in the metadata reveals.
        "extero_encoder": str(ctx.model.extero_encoder),
        # Planes per pixel in one sensor row. Without it the deploy divides the row
        # width by nothing and demands a camera N times too large -- the same trap
        # read_fm_extero_meta was fixed for.
        "extero_channels": int(getattr(ctx, "extero_channels", 1)),
        # Only for the CONVOLUTIONAL encoder. The dataset derives the geometry for any depth
        # recording, but a flat embedding is permutation-invariant over pixels, so stating
        # the fold there would have the deploy enforce a constraint that does not exist --
        # refusing a transposed camera an MLP graph would consume perfectly well.
        "extero_image_hw": ([[int(h), int(w)] for h, w in ctx.extero_image_hw]
                            if (ctx.extero_image_hw
                                and ctx.model.extero_encoder == "cnn") else None),
        "extero_tokens_per_sensor": int(ctx.model.tokens_per_sensor),
        # Which way the conditioning/future dependency runs. The deploy does not need it --
        # the graph is opaque and folds the whole sampler in -- but a loaded artifact should
        # be able to say which architecture it is, because nothing in the weights can.
        "attention_mode": str(ctx.model.attention_mode),
        # What the N history rows CONTAIN -- the applied reference, or the robot's own
        # achieved state. Same row WIDTH either way, so this is the only thing that can say
        # which, and the runtimes refuse a pair whose serving arm disagrees with it. Absent
        # in graphs exported before the flag, which are definitionally "reference".
        "history_source": str(getattr(ctx, "history_source", "reference")),
        # What the history tokens must be built from, and the re-plan period the targets
        # were cut at. Both are contracts the runtime has to honour, not descriptions: a
        # deployment feeding a measured history to a partially autoregressive model, or
        # re-planning at a different period than the horizon was sized for, is silently
        # off-distribution. ``fm_session.load_fm_context`` checks them.
        "fm_snap_every": ctx.fm_snap_every,
        # The state LAYOUT, which nothing else in the graph reveals. The generator's
        # output goes STRAIGHT into the tracker's observation now, so a layout
        # disagreement is not a bad lift -- it is a scrambled observation the policy acts
        # on. D, nj and the frame count do not pin it down (the previous relative-state
        # layout is 3 channels wider for every nj/K, close enough to look plausible; and a
        # window that drops a block is narrower but just as loadable), so the block table
        # travels explicitly -- with the SELECTION this checkpoint trained on, not the
        # full five. ``fm_session.load_fm_context`` requires it, and
        # ``GenTrackerPolicy.load`` requires it to equal the tracker's.
        "window_blocks": [[name, int(w)] for name, w in
                          window_blocks(ctx.nj, ctx.target_num_extra_frames,
                                        ctx.reference_blocks)],
        # Signals to the deploy side that the graph accepts the history_null input, so it can
        # sample with the learned null embedding before its history fills. Absent in graphs
        # exported before that input existed.
        "has_history_null": True,
        # The clip band this checkpoint TRAINED under. The deploy port must clamp the same
        # way or it is feeding a differently-bounded sensor; absent -> the per-source
        # default, which is what a pre-field graph used.
        "extero_clip": (None if ctx.extero_clip is None else float(ctx.extero_clip)),
        # The camera-latency distribution this checkpoint trained under, index = lag in
        # control steps. A SIMULATOR reads it to reproduce that latency instead of feeding a
        # fresh frame the generator never saw; hardware ignores it, because its lag is
        # physical and already in the frames. ``None`` in a graph exported before the
        # latency model, and the correct reading for one is "no synthetic lag".
        "depth_latency_probs": (list(ctx.depth_latency_probs)
                                if getattr(ctx, "depth_latency_probs", None) else None),
    }


def _refuse_privileged_extero(ctx, checkpoint: str, allow: bool) -> None:
    """Refuse to export a generator conditioned on a signal no deployment can produce.

    A dense noise-free height scan is exact ground truth over metres of terrain: there is no
    sensor that yields it, MuJoCo's port is a per-ray Python loop, and the hardware config
    exporter has no wiring for it. An ONNX graph exists to be run off-sim, so emitting one
    here would produce an artifact whose only possible use is to fail later -- and to fail
    *quietly*, because the deploy side would fall back to a coarse default grid and hand the
    model a correctly-shaped array of the wrong signal.

    Args:
        ctx: The loaded FM context.
        checkpoint: Path, for the message.
        allow: Skip the refusal (``--allow_privileged_extero``).

    Raises:
        ValueError: When the checkpoint's exteroception is marked privileged and ``allow`` is
            False.
    """
    spec = list(ctx.extero_spec or [])
    if not any(bool(s.get("privileged")) for s in spec):
        return
    detail = ", ".join(
        f"{s.get('sensor')} {s.get('size')} m @ {s.get('resolution')} m "
        f"({s.get('height')}x{s.get('width')} = {s.get('num_rays')} rays)"
        for s in spec if s.get("privileged")
    )
    if not allow:
        raise ValueError(
            f"{checkpoint} conditions on PRIVILEGED exteroception ({detail}), which no "
            "deployment can reproduce -- it is an exact noise-free ground-truth map, and it "
            "exists to bound what perception could buy, not to be run off-sim. Exporting it "
            "would yield a graph whose deploy path substitutes a coarse fallback grid and "
            "feeds the model the wrong signal at the right shape. Pass "
            "--allow_privileged_extero if you have a use that is not deployment."
        )
    print(f"[WARN] exporting a PRIVILEGED-exteroception generator ({detail}). Nothing off-sim "
          "can produce this input; the deploy path will refuse it.")


#: Graph input/output names, in ``_FmSamplerOnnx.forward`` argument order.
_IO_NAMES = ("history", "extero", "cmd_tokens", "noise", "history_null", "trajectory")


def _export_graph(wrapper: nn.Module, dummy: tuple, out_path: str, opset: int,
                  dynamic_batch: bool) -> None:
    """Trace ``wrapper`` to ONNX with the batch axis either fixed at 1 or symbolic.

    **The batch axis is fixed at 1 by default, and that is a performance decision, not a
    limitation.** A symbolic batch means every head reshape inside the 71 traced attention
    blocks has to compute its target shape at RUN time, so the graph carries a
    ``Shape -> Gather -> Unsqueeze -> Concat`` chain of int64 scalar ops per block. Those are
    shape arithmetic, which onnxruntime deliberately keeps on the HOST: measured on the
    shipped 27M depth generator, 2687 of 6606 kernel nodes landed on the
    ``CPUExecutionProvider``, and every scalar they produced then had to be copied back to
    the device -- the 71 ``MemcpyFromHost`` nodes onnxruntime warns about at load
    ("It might have negative impact on performance (including unable to run CUDA graph)").

    Fixing the axis lets constant folding delete that arithmetic outright, which

    * puts **every** node on CUDA (2687 -> 0 host nodes, 6606 -> 3052 kernel nodes),
    * lets the fusion pass match patterns the shape ops were splitting
      (``SkipLayerNormalization``, ``QuickGelu``, a fused QKV ``Split``), and
    * makes the graph eligible for **CUDA Graph capture**, which onnxruntime refuses
      outright while any node is on the host ("all compute graph nodes have not been
      partitioned to the CUDAExecutionProvider").

    Measured end to end on the shipped 27M pair, per re-plan (dynamic -> fixed -> fixed with
    capture): 11.6 -> 9.8 -> 8.3 ms on an RTX 4070, and 22.4 -> 19.3 -> 14-15 ms on the
    Jetson Thor. The Thor number is the one that matters -- the baseline sat ABOVE the 20 ms
    control period, and a chronically late plan is what the two-box bring-up traced its falls
    to. Quote Thor figures as a range: repeated passes on the same graph vary ~8% there
    (clock/thermal), where the desktop is stable to ~1%.

    Nothing on the deploy path wants a batch: ``GenTrackerPolicy`` drives one robot and
    builds every input at ``V=1``, and the Isaac side runs the model in torch rather than
    through this graph. ``dynamic_batch=True`` is kept for throughput experiments only.

    Fixing the axis changes which shapes are known at trace time, not what is computed, so
    the two graphs agree to ~1e-6 rather than exactly: with the batch known, torch folds a
    few more constants at export and rounds them once instead of per run. That is three
    orders below the ~2.6e-3 CPU-vs-CUDA spread this graph already has at fp32, and the
    fixed-axis graph is marginally the CLOSER of the two to a CPU reference. Pinned by
    ``test_fm_onnx_static_batch``.

    Args:
        wrapper: The traced :class:`_FmSamplerOnnx`.
        dummy: One example input per ``forward`` argument, all at batch 1.
        out_path: Output ``.onnx`` path.
        opset: ONNX opset.
        dynamic_batch: Declare the batch axis symbolic instead of fixing it at 1.
    """
    # Use the legacy (TorchScript) exporter: it honors dynamic_axes for the batch
    # dim on TransformerEncoder, whereas the newer dynamo path baked a static batch
    # into an internal reshape here.
    torch.onnx.export(
        wrapper, dummy, out_path,
        export_params=True, opset_version=opset, dynamo=False,
        input_names=list(_IO_NAMES[:-1]),
        output_names=[_IO_NAMES[-1]],
        dynamic_axes=({k: {0: "V"} for k in _IO_NAMES} if dynamic_batch else None),
    )
    print(f"[INFO] batch axis {'symbolic (V)' if dynamic_batch else 'fixed at 1'}")


def export_fm_onnx(
    checkpoint: str, out_path: str, opset: int = 18, allow_privileged_extero: bool = False,
    dynamic_batch: bool = False,
    advantage_label: str | None = None,
) -> dict:
    """Export ``checkpoint`` to ``out_path`` and embed ``fm_meta``; return the meta.

    Args:
        checkpoint: Path to the FM ``.pt``.
        out_path: Output ``.onnx`` path.
        opset: ONNX opset.
        allow_privileged_extero: Export even when the generator conditions on a privileged
            signal no deployment can produce. Off by default, because the whole value of an
            exported graph is that something off-sim can run it.
        dynamic_batch: Declare the batch axis symbolic (``"V"``) instead of fixing it at 1.
            Off by default; see :func:`_export_graph` for why a symbolic batch is expensive
            here and why nothing on the deploy path wants one.
        advantage_label: ``"positive"`` / ``"negative"`` / ``"null"``, BAKED IN as a constant
            for an advantage-conditioned checkpoint (required for one, refused for any
            other). It rides ``fm_meta`` so an artifact states which arm it is, since two
            graphs from one checkpoint are otherwise identical on disk.

    Returns:
        The embedded ``fm_meta`` dict.

    Raises:
        ValueError: On a non-command-conditioned checkpoint, or on a privileged-exteroception
            checkpoint without the override.
    """
    # The label goes to the LOADER too, not just the wrapper: a conditioned checkpoint with
    # no `advantage_serve_label` is refused at load, and the exporter is exactly the caller
    # that legitimately states the arm on the command line instead of reading it off the file.
    ctx = load_fm_context(checkpoint, device="cpu", advantage_label=advantage_label)
    if ctx.cmd_dim <= 0:
        raise ValueError("export_fm_onnx expects a command-conditioned checkpoint (cmd_dim>0).")
    _refuse_privileged_extero(ctx, checkpoint, allow_privileged_extero)
    conditioned = ctx.model.advantage_emb is not None
    if conditioned and advantage_label is None and ctx.advantage_label is None:
        raise ValueError(
            "this checkpoint is advantage-conditioned, so the graph must state WHICH arm it "
            "is: pass --advantage_label {positive,negative,null}. Defaulting would make the "
            "deliverable and its own control indistinguishable on disk.")
    # An unconditioned checkpoint given a label already failed at load, above.
    # Falling back to the artifact's own arm keeps `export_fm_onnx <best_positive.pt>` working
    # without restating what the file already says.
    label_id = ctx.advantage_label
    if advantage_label is not None:
        label_id = label_from_name(advantage_label)
    if label_id is not None:
        advantage_label = LABEL_NAMES[label_id]
    wrapper = _FmSamplerOnnx(ctx, label_id).eval()

    v, n, f, d, n_cmd, cmd = 1, ctx.N, ctx.F, ctx.D, ctx.num_cmd_tokens, ctx.cmd_dim
    # FLAT exteroception width: one token per sensor (176-ray scan) or one per camera
    # (2 x 780 depth). The model reshapes to (B, T, extero_sensor_dim) internally.
    edim = int(ctx.model.extero_sensor_count) * int(ctx.model.extero_sensor_dim)
    # One dummy per _FmSamplerOnnx.forward arg, in order:
    # (history, extero, cmd_tokens, noise, history_null). ``extero`` is the FLAT width, so a
    # depth FM traces at 2*780 rather than the scan's 176 -- do NOT use extero_sensor_dim alone here.
    dummy = (torch.randn(v, n, d), torch.randn(v, edim), torch.randn(v, n_cmd, cmd),
             torch.randn(v, f, d), torch.zeros(v, 1))
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    _export_graph(wrapper, dummy, out_path, opset, dynamic_batch)

    meta = _fm_meta(ctx)
    meta["advantage_label"] = advantage_label
    model = onnx.load(out_path)
    entry = onnx.StringStringEntryProto(key="fm_meta", value=json.dumps(meta))
    model.metadata_props.append(entry)
    onnx.save(model, out_path)
    print(f"[INFO] Wrote {out_path}\n[INFO] fm_meta: {json.dumps(meta)}")
    return meta


def main() -> None:
    """CLI entry point."""
    p = argparse.ArgumentParser(description="Export a flow-matching checkpoint to ONNX.")
    p.add_argument("--checkpoint", required=True, help="Path to the FM .pt checkpoint.")
    p.add_argument("--out", default=None, help="Output .onnx path (default: alongside the checkpoint).")
    p.add_argument("--opset", type=int, default=18)
    p.add_argument(
        "--dynamic_batch", action="store_true", default=False,
        help="Declare the batch axis symbolic instead of fixing it at 1. Costs ~2700 "
             "host-side shape-arithmetic nodes and rules out CUDA Graph capture (see "
             "_export_graph); nothing on the deploy path needs it.")
    p.add_argument(
        "--allow_privileged_extero", action="store_true", default=False,
        help="Export even when the generator conditions on a PRIVILEGED signal (an exact "
             "noise-free dense height scan). Refused by default: no deployment can produce "
             "it, so the graph could only fail later -- and would fail quietly, because the "
             "deploy path substitutes a coarse fallback grid.")
    p.add_argument(
        "--advantage_label", default=None, choices=("positive", "negative", "null"),
        help="Bake this advantage label into the graph as a constant. REQUIRED for an "
             "advantage-conditioned checkpoint and refused for any other. It is a constant "
             "at inference, so it never becomes a graph input and the whole deploy-side "
             "contract is untouched; the negative arm is simply a second export.")
    args = p.parse_args()
    # Named for the checkpoint, so exporting a second generator beside the first does not
    # overwrite it and the filename says which model it holds (deploy.artifacts). The label
    # joins that name for the same reason: `<run>_fm.onnx` and its negative control come from
    # ONE checkpoint and differ only in a constant inside the graph.
    out = args.out or os.path.join(os.path.dirname(args.checkpoint),
                                   fm_artifact_name(args.checkpoint))
    if args.advantage_label and not args.out:
        stem, ext = os.path.splitext(out)
        out = f"{stem[:-3]}_{args.advantage_label}_fm{ext}" if stem.endswith("_fm") \
            else f"{stem}_{args.advantage_label}{ext}"
    export_fm_onnx(args.checkpoint, out, args.opset,
                   allow_privileged_extero=args.allow_privileged_extero,
                   dynamic_batch=args.dynamic_batch,
                   advantage_label=args.advantage_label)


if __name__ == "__main__":
    main()
