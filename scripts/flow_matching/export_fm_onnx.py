"""Export a flow-matching generator checkpoint to a self-contained ONNX file.

The exported graph wraps the :class:`FlowMatchingTransformer` together with the
**noise-input, unrolled** Euler sampler and **folds in the normalizers**, so a
deployment runtime (numpy + onnxruntime, see ``transfer/deploy``) feeds the *raw*
history token + *raw* future command + sampling noise and gets the *denormalized*
relative-state prediction back -- no torch, no separate normalizer stats.

  inputs : history_token (V, H, Din)   raw relative-state-+-command token
           future_cmd    (V, F, cmd)   raw future target_vel horizon
           noise         (V, F, D)      x0 ~ N(0, I) (generated by the caller)
  output : trajectory    (V, F, D)      denormalized relative-state prediction

The world-frame lift (``state_to_absolute``) and the history-token construction
(``relative_state``) stay in the deployment glue -- they are cheap geometry that
needs the per-step anchor. Deployment metadata (frame names, dims, num_steps,
joint order) is embedded in the ONNX ``metadata_props`` under key ``fm_meta``.

Usage:
    python scripts/flow_matching/export_fm_onnx.py \
        --checkpoint logs/flow_matching/<run>/ckpt_<n>.pt \
        --out logs/flow_matching/<run>/fm.onnx
"""

from __future__ import annotations

import argparse
import json
import os

import onnx
import torch
import torch.nn as nn

from robot_rl.flow_matching.online import load_fm_context, FmOnlineContext


class _FmSamplerOnnx(nn.Module):
    """ONNX-exportable wrapper: raw inputs -> denormalized relative-state prediction.

    Folds the history-token normalization, future-command normalization, and the
    target denormalization into the graph, and unrolls the ``num_steps`` Euler
    integration of the learned flow (encoder runs once, decoder per step).
    """

    def __init__(self, ctx: FmOnlineContext):
        """Capture the model + normalizer statistics as buffers from a loaded context."""
        super().__init__()
        self.model = ctx.model
        self.num_steps = int(ctx.num_steps)
        self.future_cmd_dim = int(ctx.future_cmd_dim)
        self.history_D = int(ctx.history_D)
        self.register_buffer("h_mean", ctx.history_norm.mean.detach().clone())
        self.register_buffer("h_std", ctx.history_norm.std.detach().clone())
        self.register_buffer("t_mean", ctx.target_norm.mean.detach().clone())
        self.register_buffer("t_std", ctx.target_norm.std.detach().clone())

    def forward(
        self, history_token: torch.Tensor, future_cmd: torch.Tensor, noise: torch.Tensor
    ) -> torch.Tensor:
        """Normalize, encode, Euler-sample with ``noise``, and denormalize."""
        hn = (history_token - self.h_mean) / self.h_std
        memory = self.model.encode(hn)

        c0, c1 = self.history_D, self.history_D + self.future_cmd_dim
        fc = (future_cmd - self.h_mean[c0:c1]) / self.h_std[c0:c1]

        x = noise
        dt = 1.0 / self.num_steps
        for i in range(self.num_steps):
            # Batch-derived tau (B,) so the graph stays dynamic in the batch axis
            # without a shape-dependent torch.full.
            tau = noise[:, 0, 0] * 0.0 + (i * dt)
            v = self.model(x, tau, memory, fc)
            x = x + dt * v
        return x * self.t_std + self.t_mean


def _fm_meta(ctx: FmOnlineContext) -> dict:
    """Deployment metadata embedded in the ONNX (replaces the .pt config/meta)."""
    return {
        "joint_names": list(ctx.joint_names),
        "history_frame_names": list(ctx.history_frame_names),
        "target_frame_names": list(ctx.target_frame_names),
        "H": ctx.H, "F": ctx.F, "D": ctx.D, "history_D": ctx.history_D, "Din": ctx.Din,
        "nj": ctx.nj, "num_steps": ctx.num_steps,
        "cmd_dim": ctx.cmd_dim, "future_cmd_dim": ctx.future_cmd_dim, "scan_dim": ctx.scan_dim,
    }


def export_fm_onnx(checkpoint: str, out_path: str, opset: int = 18) -> dict:
    """Export ``checkpoint`` to ``out_path`` and embed ``fm_meta``; return the meta."""
    ctx = load_fm_context(checkpoint, device="cpu")
    wrapper = _FmSamplerOnnx(ctx).eval()

    v, H, F, Din, D, cmd = 1, ctx.H, ctx.F, ctx.Din, ctx.D, ctx.future_cmd_dim
    dummy = (torch.randn(v, H, Din), torch.randn(v, F, cmd), torch.randn(v, F, D))
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    # Use the legacy (TorchScript) exporter: it honors dynamic_axes for the
    # batch dim on TransformerEncoder/Decoder, whereas the newer dynamo path
    # baked a static batch into an internal reshape here.
    torch.onnx.export(
        wrapper, dummy, out_path,
        export_params=True, opset_version=opset, dynamo=False,
        input_names=["history_token", "future_cmd", "noise"], output_names=["trajectory"],
        dynamic_axes={k: {0: "V"} for k in ("history_token", "future_cmd", "noise", "trajectory")},
    )

    meta = _fm_meta(ctx)
    model = onnx.load(out_path)
    entry = onnx.StringStringEntryProto(key="fm_meta", value=json.dumps(meta))
    model.metadata_props.append(entry)
    onnx.save(model, out_path)
    print(f"[INFO] Wrote {out_path}\n[INFO] fm_meta: {json.dumps(meta)}")
    return meta


def main() -> None:
    """CLI entry point."""
    p = argparse.ArgumentParser(description="Export a flow-matching checkpoint to ONNX.")
    p.add_argument("--checkpoint", required=True, help="Path to the FM .pt checkpoint.")
    p.add_argument("--out", default=None, help="Output .onnx path (default: alongside the checkpoint).")
    p.add_argument("--opset", type=int, default=18)
    args = p.parse_args()
    out = args.out or os.path.join(os.path.dirname(args.checkpoint), "fm.onnx")
    export_fm_onnx(args.checkpoint, out, args.opset)


if __name__ == "__main__":
    main()
