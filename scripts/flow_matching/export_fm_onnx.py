"""Export a robot-state-conditioned flow-matching checkpoint to a self-contained ONNX.

The exported graph wraps the :class:`FlowMatchingTransformer` together with the
**noise-input, unrolled** Euler sampler (no inpainting / known mask) and **folds in
the normalizers**, so a deployment runtime (numpy + onnxruntime, see
``transfer/deploy``) feeds the *raw* history (phase) tokens + *raw* exteroception
tokens + *raw* strided command tokens + sampling noise and gets the *denormalized*
relative-state future window back -- no torch, no separate normalizer stats.

  inputs : history     (V, N, D)          raw relative-state history (phase) tokens
           extero      (V, T*extero_dim)  raw exteroception tokens, flattened: the
                                          176-ray height scan (T=1) or one 780-value
                                          depth image per camera (T=2)
           cmd_tokens  (V, n_cmd, cmd)    raw strided commanded-velocity tokens
           noise       (V, F, D)          x0 ~ N(0, I) (generated by the caller)
  output : trajectory  (V, F, D)          denormalized relative-state FUTURE window;
                                          all F frames are novel (node 0 = "now")

The world-frame lift (``state_to_absolute``) and the conditioning construction
(``relative_state`` for the history + the sensor read) stay in the deployment glue --
they are cheap geometry that needs the per-step anchor.  Deployment metadata (frame
names, dims, num_steps, joint order, ``ground_z``, which sensor feeds the exteroception
tokens and its camera contract) is embedded in the ONNX ``metadata_props`` under key
``fm_meta``.

Usage:
    python scripts/flow_matching/export_fm_onnx.py \
        --checkpoint logs/flow_matching/<run>/ckpt_<n>.pt \
        --out logs/flow_matching/<run>/fm.onnx
"""

from __future__ import annotations

import argparse
import json
import os

import onnx
import torch
import torch.nn as nn

from robot_rl.flow_matching.online import load_fm_context, FmOnlineContext


class _FmSamplerOnnx(nn.Module):
    """ONNX-exportable wrapper: raw inputs -> denormalized relative-state future window.

    Folds the history/height/command normalization and the target denormalization
    into the graph, and unrolls the ``num_steps`` Euler integration of the learned
    flow. The history/height/command are separate conditioning tokens (held fixed
    across integration); the F future tokens are the only denoised ones -- there is
    no inpainting / known mask / re-clamp.
    """

    def __init__(self, ctx: FmOnlineContext):
        """Capture the model + normalizer statistics as buffers from a loaded context."""
        super().__init__()
        self.model = ctx.model
        self.num_steps = int(ctx.num_steps)
        self.register_buffer("s_mean", ctx.state_norm.mean.detach().clone())
        self.register_buffer("s_std", ctx.state_norm.std.detach().clone())
        self.register_buffer("c_mean", ctx.cmd_norm.mean.detach().clone())
        self.register_buffer("c_std", ctx.cmd_norm.std.detach().clone())
        self.register_buffer("h_mean", ctx.height_norm.mean.detach().clone())
        self.register_buffer("h_std", ctx.height_norm.std.detach().clone())

    def forward(
        self,
        history: torch.Tensor,
        extero: torch.Tensor,
        cmd_tokens: torch.Tensor,
        noise: torch.Tensor,
        history_null: torch.Tensor,
    ) -> torch.Tensor:
        """Normalize the conditioning, Euler-sample the F future from ``noise``, denormalize.

        ``history_null`` is a ``(V, 1)`` float flag (>0.5 = null) rather than a bool, because a
        bool graph input is awkward across runtimes; it selects the model's learned
        ``null_history`` embedding in place of the history content. That is what lets the
        deployed generator sample before its history window has filled, matching the RL side.
        """
        hist_n = (history - self.s_mean) / self.s_std        # (V, N, D)
        height_n = (extero - self.h_mean) / self.h_std       # (V, T*extero_dim)
        cmd_n = (cmd_tokens - self.c_mean) / self.c_std      # (V, n_cmd, cmd)
        null_m = (history_null.reshape(-1) > 0.5)            # (V,) bool

        x = noise                                            # (V, F, D) -- all F denoised
        dt = 1.0 / self.num_steps
        for i in range(self.num_steps):
            # Batch-derived tau (V,) so the graph stays dynamic in the batch axis.
            tau = noise[:, 0, 0] * 0.0 + (i * dt)
            v = self.model(x, tau, hist_n, height_n, cmd_n, history_null_mask=null_m)
            x = x + dt * v
        return x * self.s_std + self.s_mean


def _fm_meta(ctx: FmOnlineContext) -> dict:
    """Deployment metadata embedded in the ONNX (replaces the .pt config/meta)."""
    return {
        "joint_names": list(ctx.joint_names),
        "target_frame_names": list(ctx.target_frame_names),
        "N": ctx.N, "F": ctx.F, "D": ctx.D, "nj": ctx.nj, "num_steps": ctx.num_steps,
        "cmd_dim": ctx.cmd_dim, "cmd_steps": list(ctx.cmd_steps), "num_cmd_tokens": ctx.num_cmd_tokens,
        "ground_z": float(ctx.ground_z), "height_dim": int(ctx.model.height_dim),
        # Which sensor feeds the exteroception tokens, how many there are, and -- for the
        # depth cameras -- their full contract, so the deployment feeds the right reading
        # and can verify it describes the same physical sensor as the tracker's.
        "extero_source": str(ctx.extero_source),
        "extero_tokens": int(ctx.model.extero_tokens),
        "extero_spec": ctx.extero_spec,
        # Signals to the deploy side that the graph accepts the history_null input, so it can
        # sample with the learned null embedding before its history fills. Absent in graphs
        # exported before that input existed.
        "has_history_null": True,
    }


def export_fm_onnx(checkpoint: str, out_path: str, opset: int = 18) -> dict:
    """Export ``checkpoint`` to ``out_path`` and embed ``fm_meta``; return the meta."""
    ctx = load_fm_context(checkpoint, device="cpu")
    if ctx.cmd_dim <= 0:
        raise ValueError("export_fm_onnx expects a command-conditioned checkpoint (cmd_dim>0).")
    wrapper = _FmSamplerOnnx(ctx).eval()

    v, n, f, d, n_cmd, cmd = 1, ctx.N, ctx.F, ctx.D, ctx.num_cmd_tokens, ctx.cmd_dim
    # FLAT exteroception width: one token per sensor (176-ray scan) or one per camera
    # (2 x 780 depth). The model reshapes to (B, T, height_dim) internally.
    edim = int(ctx.model.extero_tokens) * int(ctx.model.height_dim)
    # One dummy per _FmSamplerOnnx.forward arg, in order:
    # (history, extero, cmd_tokens, noise, history_null). ``extero`` is the FLAT width, so a
    # depth FM traces at 2*780 rather than the scan's 176 -- do NOT use height_dim alone here.
    dummy = (torch.randn(v, n, d), torch.randn(v, edim), torch.randn(v, n_cmd, cmd),
             torch.randn(v, f, d), torch.zeros(v, 1))
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    # Use the legacy (TorchScript) exporter: it honors dynamic_axes for the batch
    # dim on TransformerEncoder, whereas the newer dynamo path baked a static batch
    # into an internal reshape here.
    torch.onnx.export(
        wrapper, dummy, out_path,
        export_params=True, opset_version=opset, dynamo=False,
        input_names=["history", "extero", "cmd_tokens", "noise", "history_null"],
        output_names=["trajectory"],
        dynamic_axes={k: {0: "V"} for k in ("history", "extero", "cmd_tokens", "noise", "trajectory", "history_null")},
    )

    meta = _fm_meta(ctx)
    model = onnx.load(out_path)
    entry = onnx.StringStringEntryProto(key="fm_meta", value=json.dumps(meta))
    model.metadata_props.append(entry)
    onnx.save(model, out_path)
    print(f"[INFO] Wrote {out_path}\n[INFO] fm_meta: {json.dumps(meta)}")
    return meta


def main() -> None:
    """CLI entry point."""
    p = argparse.ArgumentParser(description="Export a flow-matching checkpoint to ONNX.")
    p.add_argument("--checkpoint", required=True, help="Path to the FM .pt checkpoint.")
    p.add_argument("--out", default=None, help="Output .onnx path (default: alongside the checkpoint).")
    p.add_argument("--opset", type=int, default=18)
    args = p.parse_args()
    out = args.out or os.path.join(os.path.dirname(args.checkpoint), "fm.onnx")
    export_fm_onnx(args.checkpoint, out, args.opset)


if __name__ == "__main__":
    main()
