"""PURE stair-tile clips: a looped stride played down (or up) a long platform-less staircase.

A pure stair tile has no approach and no exit -- the robot is on the treads from the first frame to
the last -- so there is nothing for Motion Bricks to in-between, which is why
``mb_plan_library._stair_tile_specs`` hardcodes ``n_pure=0`` and the MB pipeline emits only
``transition`` tiles. This script covers the other half, and it needs none of the MB machinery
either: a pure clip is the reference stride looped along the tile, placed with the SAME
:func:`~motion_gen.terrain.terrain_place.place_periodic_on_tile` the MB transition path uses.

It exists because that half used to come from ``generate_box_clips.py``, which is DEPRECATED
("part of the motion-matching / DP clip generator, retained for ablation studies only... Not on the
live pipeline") and pulls in the motion-matching candidate graph at import time. The pure path never
touched the matcher, so nothing about it needed to live there -- it was there because the DP
generator originally produced all terrain. Consequences of the old arrangement, both real:

* the live pipeline's ``terrain`` family (1500 clips, ~14% of ``g1_mb_v5``'s time) was generated by a
  script marked deprecated, and had to be stapled back on with ``--extra-mix``;
* its speed band came from a hand-computed ``--transition-vels`` string that had to be kept equal to
  the MB stair band by eye. It was: 50 levels from 0.6 to 2.6, matching ``--stair-vel-range``
  exactly, which is why the ``terrain`` and ``transition`` families measured identically.

Here the band is ``--stair-vel-range``, the same flag ``mb_plan_library`` takes, so the two stair
families cannot drift apart. The band selects which reference each clip plays; the command WRITTEN
into the clip is the speed that traversal actually achieves, so it is aligned with the motion (see
the note at the ``tvel`` assignment). Runs with NO IsaacLab and no Motion Bricks. Example::

    PYTHONPATH=source/motion_gen:source/robot_rl python scripts/rsl_rl/mb_pure_stair_clips.py \
        --source hf/trajectories/retargeted/2026-06-13_15-10-58_merged \
        --terrain-lib trajectories/skills/library_v2 --terrain-skills stairs_up \
        --n-tiles 15 --clips-per-tile 50 --out clips/_mb_families/family_pure_stairs_up.h5
"""

from __future__ import annotations

import argparse

import numpy as np
import torch

from motion_gen.clip_output import ClipOutputBuilder
from motion_gen.clips.clip_io import ClipLibraryWriter, load_clip_library
from motion_gen.ingest.terrain_ingest import ingest_terrain_library
from motion_gen.joint_names import world_position_channels
from motion_gen.library_metadata import read_library_metadata
from motion_gen.terrain.box_clip import build_anchor_mask_t, stair_tile_boxes
from motion_gen.terrain.terrain_place import place_periodic_on_tile
from motion_gen.terrain.terrain_sampler import sample_stair_tiles
from motion_gen.world_lift import _ANCHOR_MASK_BOX

# Kept identical to the MB emitter (``motionbricks.terrain_splice._VARIANT_KEYS``) so an overlay this
# script writes is indistinguishable from one the transition path writes.
_VARIANT_KEYS = ("variant", "slab_thickness", "leg_size", "leg_inset")
_CONTACT = ["left_ankle_roll_link", "right_ankle_roll_link"]


def _pad_or_trim(t: torch.Tensor, T: int) -> torch.Tensor:
    """Pad (repeating the last frame) or trim a ``[t0, ...]`` tensor to length ``T`` along dim 0."""
    n = t.shape[0]
    if n == T:
        return t
    if n > T:
        return t[:T]
    return torch.cat([t, t[-1:].expand((T - n,) + tuple(t.shape[1:]))], dim=0)


def _float_thickness(tile) -> float:
    """Floating-tread slab thickness (m) for a stair ``tile``; ``0`` = solid treads.

    The stair-decor policy resolves one dict per stair band and a tiles-then-clips tile has exactly
    one band, so band 0 carries the tile's thickness.
    """
    return float(tile.stair_decor[0]["float_thickness"]) if tile.stair_decor else 0.0


def _speeds(lo: float, hi: float, n: int) -> list[float]:
    """``n`` evenly spaced commanded speeds over ``[lo, hi]`` -- the stair band, tiled.

    Matches ``mb_plan_library._clip_speeds``' stair branch exactly (inclusive of both ends), so the
    two stair families sample the same grid rather than two hand-matched ones.
    """
    lo, hi = float(lo), float(hi)
    return [lo] if n <= 1 else [lo + (hi - lo) * i / (n - 1) for i in range(n)]


def _achieved_vx(Wp, dt: float) -> float:
    """Mean forward speed the placed traversal actually achieves (m/s), along the tile's +x."""
    n = int(Wp.shape[0])
    if n < 2:
        return 0.0
    return float((Wp[-1, 0] - Wp[0, 0]) / max((n - 1) * float(dt), 1e-6))


def _pure_clip(builder, ts, tile, args, dev, steady_vx: float) -> dict:
    """One looped-traversal clip on a fixed pure stair ``tile`` -> record dict.

    The tile's geometry is authored from the tile, not the motion, and the datum is the boxes alone,
    so every clip on this ``terrain_id`` emits byte-identical geometry -- the reuse invariant the RL
    importer depends on (it meshes ONE tile per terrain_id from ONE manifest entry).
    """
    going_up = float(ts.terrain_meta.get("terrain", {}).get("direction_z", -1)) > 0
    boxes = stair_tile_boxes(step_height=tile.step_height, step_depth=tile.step_depth,
                             num_steps=int(tile.stair_steps[0]), tread_width=tile.width,
                             ttype="terrain", going_up=going_up,
                             float_thickness=_float_thickness(tile))
    Wp, Wq, Wj, terr_contact = place_periodic_on_tile(
        ts, tile, boxes, dev, k=0, going_up=going_up, end_buffer_treads=args.end_buffer)
    m = float(args.footprint_margin)
    bxy = torch.tensor([[float(b["pos"][0]), float(b["pos"][1])] for b in boxes])
    bhf = torch.tensor([[float(b["size"][0]) / 2.0, float(b["size"][1]) / 2.0] for b in boxes])
    box_lo, box_hi = (bxy - bhf).amin(0), (bxy + bhf).amax(0)
    lo = torch.minimum(Wp[:, :2].amin(0), box_lo)
    hi = torch.maximum(Wp[:, :2].amax(0), box_hi)
    corner = box_lo - m                                # clip-independent datum: the fixed boxes
    Wp = Wp.clone()
    Wp[:, 0] -= corner[0]
    Wp[:, 1] -= corner[1]

    y, dy, contact = builder.build(Wp, Wq, Wj, args.dt)
    T = int(Wp.shape[0])
    if terr_contact is not None:
        contact[0:T] = terr_contact[:T].to(contact.dtype)
    amt = build_anchor_mask_t(T, [(0, T)], [_ANCHOR_MASK_BOX], device=dev)
    overlays = [{"kind": "box",
                 "pos_xy": [b["pos"][0] - float(corner[0]), b["pos"][1] - float(corner[1])],
                 "size_xyz": [float(v) for v in b["size"]],
                 "base_z": float(b["pos"][2] - b["size"][2] / 2.0),
                 "walkable_top": True, "yaw": float(b["yaw"]),
                 **{k: b[k] for k in _VARIANT_KEYS if k in b}} for b in boxes]
    # frame_yaw 0 is CORRECT: place_periodic_on_tile yaw-normalizes the traversal onto the tile's +x.
    manifest = {"terrain_id": int(tile.terrain_id), "type": "terrain",
                "size_x": float(hi[0] - lo[0]) + 2 * m, "size_y": float(hi[1] - lo[1]) + 2 * m,
                "overlays": overlays, "frame_yaw": 0.0, "has_floor": bool(tile.has_floor)}
    # ONE constant command, equal to the speed the looped traversal ACTUALLY achieves.
    #
    # A pure tile is stairs from the first frame to the last, and its motion is a fixed looped
    # replay -- it cannot track a command at all. So the rule "the motion tracks the command except
    # where terrain overrides" means the override covers the WHOLE clip here, and a varying command
    # would be misaligned for 100% of it: the worst case, not a feature. (An earlier version did
    # exactly that.) Pinning the command to the achieved speed instead makes it aligned by
    # construction, which is the closest a pure tile can get to the contract.
    #
    # ``steady_vx`` -- the speed the tile's reference was SELECTED for -- is only the nearest solved
    # stride, so it is not what the motion does; measuring the placement is.
    tvel = torch.zeros(T, 3, dtype=torch.float32, device=dev)
    tvel[:, 0] = float(_achieved_vx(Wp, float(args.dt)))
    return {"y": y, "dy": dy, "contact": contact, "anchor_mask_t": amt, "target_vel": tvel,
            "terrain_id": int(tile.terrain_id), "n": T, "manifest": manifest, "name": ts.name,
            "corner": (float(corner[0]), float(corner[1]))}


def _widen_treads_to_motion(tile_recs: list[dict], builder, m: float) -> tuple[float, float]:
    """Widen a pure tile's treads to the union lateral extent of ALL its clips + margin, in place.

    The looped placement accumulates lateral drift, so over a long traversal the robot walks off the
    authored tread width and onto whatever is a riser below. There is no platform on a pure tile, so
    every tread widens (the transition path can instead widen only its platforms).

    All clips on the tile share ONE geometry, so the width is computed once from their union and
    written identically to each, and the clips are re-shifted in y so that union sits at ``m``.

    TODO(stair-lateral-drift): the real fix is to correct the accumulated drift in the looped
    placement -- keep the traversal on the tread centerline -- rather than widening the treads to
    cover wherever it wandered. Carried over from the path this replaces.
    """
    py = world_position_channels(builder.pos_names, "y")
    ylo = min(float(np.asarray(r["y"])[:, py].min()) for r in tile_recs)
    yhi = max(float(np.asarray(r["y"])[:, py].max()) for r in tile_recs)
    for o in tile_recs[0]["manifest"]["overlays"]:
        ylo = min(ylo, o["pos_xy"][1] - o["size_xyz"][1] / 2.0)
        yhi = max(yhi, o["pos_xy"][1] + o["size_xyz"][1] / 2.0)
    span = max(yhi - ylo, 1e-6)
    size_y = span + 2.0 * m
    shift = m - ylo
    size_x = float(tile_recs[0]["manifest"]["size_x"])
    for r in tile_recs:
        yy = np.asarray(r["y"])
        yy[:, py] += shift
        overlays = []
        for o in tile_recs[0]["manifest"]["overlays"]:
            o2 = dict(o)
            o2["size_xyz"] = [o["size_xyz"][0], size_y, o["size_xyz"][2]]
            o2["pos_xy"] = [o["pos_xy"][0], size_y / 2.0]
            overlays.append(o2)
        r["manifest"] = dict(r["manifest"])
        r["manifest"].update(size_x=size_x, size_y=size_y, overlays=overlays)
    return size_x, size_y


def main() -> int:
    """Generate one pure-stair family library."""
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--source", required=True, help="Traj-opt library root (channel layout).")
    p.add_argument("--terrain-lib", default="trajectories/skills/library_v2",
                   help="Terrain library holding the solved stair strides.")
    p.add_argument("--terrain-hf-repo", default="zolkin/robot_rl")
    p.add_argument("--terrain-skills", default="stairs_up",
                   help="ONE stair direction per invocation (stairs_up or stairs_down), so the "
                        "output is one family .h5 the composer can mix by tile count.")
    p.add_argument("--out", required=True, help="Output family .h5.")
    p.add_argument("--n-tiles", type=int, default=15, help="Pure stair tiles to sample.")
    p.add_argument("--clips-per-tile", type=int, default=50,
                   help="Commanded speeds per tile, evenly spaced over --stair-vel-range.")
    p.add_argument("--stair-vel-range", type=float, nargs=2, default=(0.2, 2.6),
                   metavar=("MIN", "MAX"),
                   help="Commanded speed band. SAME flag and default as mb_plan_library, so the "
                        "pure and transition stair families share one band by construction.")
    p.add_argument("--pure-seconds", type=float, default=6.0,
                   help="Tile LENGTH, expressed as seconds at the stride's horizontal speed. Note "
                        "the resulting CLIP runs about 2x longer than this: climbing covers ground "
                        "more slowly than the flat-projected stride speed used to size the tile. "
                        "Measured on library_v2 stairs_up: 4 s -> 277 steps, 8 s -> 737, 12 s -> "
                        "1197, so 6 s lands near g1_mb_v5's terrain family (378-880, median 515).")
    p.add_argument("--end-buffer", type=int, default=3, help="Treads left spare at the tile end.")
    p.add_argument("--warn-steps", type=int, default=1000,
                   help="Warn if a clip exceeds this many steps. The COMPOSED library's num_steps is "
                        "the max over all families, so one long family pads every other clip up to "
                        "its length -- an overrun here costs memory library-wide, not just here.")
    p.add_argument("--tile-width-range", type=float, nargs=2, default=(1.0, 1.6),
                   metavar=("MIN", "MAX"))
    p.add_argument("--n-steps-range", type=int, nargs=2, default=(4, 10), metavar=("MIN", "MAX"))
    p.add_argument("--stair-floor-frac", type=float, default=0.5,
                   help="Fraction of tiles with a flat ground plane under the stairs.")
    p.add_argument("--stair-float-frac", type=float, default=0.0,
                   help="Fraction of tiles with FLOATING treads.")
    p.add_argument("--stair-float-thick-range", type=float, nargs=2, default=(0.03, 0.06),
                   metavar=("MIN", "MAX"))
    p.add_argument("--footprint-margin", type=float, default=1.0)
    p.add_argument("--tile-seed", type=int, default=0)
    p.add_argument("--dt", type=float, default=0.02)
    p.add_argument("--device", default="cpu")
    args = p.parse_args()

    dev = torch.device(args.device)
    skills = [s.strip() for s in args.terrain_skills.split(",") if s.strip()]
    if len(skills) != 1:
        raise SystemExit(f"--terrain-skills must name exactly ONE direction, got {skills}")
    lib_meta = read_library_metadata(args.source)
    builder = ClipOutputBuilder(lib_meta.pos_output_names, lib_meta.vel_output_names,
                               contact_frames=_CONTACT, device=dev)

    print(f"[pure] ingesting {args.terrain_lib} ({skills[0]}) ...")
    srcs = ingest_terrain_library(args.terrain_lib, hf_repo=args.terrain_hf_repo, dt=args.dt,
                                  device=dev, skills=skills)
    if not srcs:
        raise SystemExit(f"no terrain sources for {skills[0]} in {args.terrain_lib}")

    # (riser, tread) -> [(source, natural speed)]. Riser/tread are CRITICAL: feet only land on treads
    # whose geometry the played stride was solved for, so a tile plays the source matching ITS
    # geometry, then the nearest natural speed within it.
    variants: dict[tuple[float, float], list[tuple[object, float]]] = {}
    for ts in srcs:
        tm = ts.terrain_meta["terrain"]
        key = (round(float(tm["riser"]), 4), round(float(tm["tread"]), 4))
        dur = max((ts.root_pos.shape[0] - 1) * args.dt, 1e-6)
        vx = float(torch.norm(ts.root_pos[-1, :2] - ts.root_pos[0, :2]) / dur)
        variants.setdefault(key, []).append((ts, vx))
    hd_grid = sorted(variants)
    nat = float(np.median([v for lst in variants.values() for _, v in lst]))
    pure_len = float(args.pure_seconds) * max(nat, 1e-3)
    speeds = _speeds(*args.stair_vel_range, args.clips_per_tile)
    print(f"[pure] {len(srcs)} sources, {len(hd_grid)} (riser,tread) variants {hd_grid}; "
          f"natural stride speed {nat:.2f} m/s -> tile length ~{pure_len:.0f} m")
    print(f"[pure] {args.n_tiles} tiles x {len(speeds)} speeds "
          f"[{speeds[0]:.2f} .. {speeds[-1]:.2f}] = {args.n_tiles * len(speeds)} clips; "
          f"command = each traversal's ACHIEVED speed (constant per clip)")

    tiles = sample_stair_tiles(
        np.random.default_rng(args.tile_seed), hd_grid=hd_grid,
        n_pure=int(args.n_tiles), n_transition=0,
        pure_length=pure_len, transition_length=max(12.0, pure_len),
        width_range=tuple(args.tile_width_range), num_steps_range=tuple(args.n_steps_range),
        lead_in_range=(1.5, 4.0), end_platform=1.0, inter_flat_range=(3.0, 5.0),
        nav_width_range=tuple(args.tile_width_range), flat_width_margin=0.3,
        single_step_frac=0.0, floor_frac=float(args.stair_floor_frac),
        decor_params={"float_frac": float(args.stair_float_frac),
                      "float_thick_range": tuple(args.stair_float_thick_range)})
    tiles = [t for t in tiles if t.ttype == "terrain"]
    if not tiles:
        raise SystemExit("sample_stair_tiles returned no pure tiles")

    records: list[dict] = []
    for tile in tiles:
        tile_recs = []
        for vx in speeds:
            # Nearest geometry, then nearest natural speed within it.
            key = min(variants, key=lambda k: (k[0] - tile.step_height) ** 2
                      + (k[1] - tile.step_depth) ** 2)
            ts = min(variants[key], key=lambda sv: abs(sv[1] - vx))[0]
            try:
                tile_recs.append(_pure_clip(builder, ts, tile, args, dev, vx))
            except Exception as e:                      # noqa: BLE001 -- skip the clip, keep the tile
                print(f"[pure][WARN] tile {tile.terrain_id} vx={vx:.2f}: skipped ({e})")
        if not tile_recs:
            print(f"[pure][WARN] tile {tile.terrain_id}: no clips, dropped")
            continue
        sx, sy = _widen_treads_to_motion(tile_recs, builder, float(args.footprint_margin))
        print(f"[pure] tile {tile.terrain_id}: {len(tile_recs)} clips, "
              f"{int(tile.stair_steps[0])} steps, footprint {sx:.1f} x {sy:.1f} m")
        records.extend(tile_recs)
    if not records:
        raise SystemExit("no clips generated")

    T = max(int(r["n"]) for r in records)
    lens = np.array([int(r["n"]) for r in records])
    print(f"[pure] clip_len: min {lens.min()} max {lens.max()} median {int(np.median(lens))} "
          f"-> {T * args.dt:.1f} s at the longest")
    if T > int(args.warn_steps):
        print(f"[pure][WARN] longest clip is {T} steps > --warn-steps {args.warn_steps}. The composed "
              f"library's num_steps is the max over families, so EVERY clip in it gets padded to "
              f"{T}. Lower --pure-seconds (clip steps run ~2x it x 100) if that is not intended.")
    meta = {"dt": args.dt, "clip_length_s": T * args.dt, "num_steps": int(T),
            "pos_output_names": list(builder.pos_names),
            "vel_output_names": list(builder.vel_names),
            "contact_frames": _CONTACT, "ref_frame": "pelvis_link",
            "skill_list": lib_meta.skill_list}
    writer = ClipLibraryWriter(args.out, len(records), meta)
    writer.set_attr("generator", "pure_stair_loop")
    writer.set_attr("terrain_manifest", [r["manifest"] for r in records])
    for i, r in enumerate(records):
        writer.write_batch(i, {
            "y_des": _pad_or_trim(torch.as_tensor(r["y"]), T).unsqueeze(0),
            "dy_des": _pad_or_trim(torch.as_tensor(r["dy"]), T).unsqueeze(0),
            "contact": _pad_or_trim(r["contact"], T).unsqueeze(0),
            "skill_id": torch.zeros(1, T, dtype=torch.uint8, device=dev),
            "stride_idx": torch.full((1, T), -1, dtype=torch.int32, device=dev),
            "target_vel": _pad_or_trim(r["target_vel"], T).unsqueeze(0),
            "terrain_id": torch.tensor([r["terrain_id"]], dtype=torch.int32, device=dev),
            "terrain_type": r["manifest"]["type"],
            "clip_len": torch.tensor([int(r["n"])], dtype=torch.int32, device=dev),
            "anchor_mask": torch.tensor([_ANCHOR_MASK_BOX], dtype=torch.uint8, device=dev),
            "anchor_mask_t": _pad_or_trim(r["anchor_mask_t"], T).unsqueeze(0),
        })
    writer.close()

    lib = load_clip_library(args.out)
    yy = torch.as_tensor(lib.y_des)
    tv = np.asarray(lib.target_vel)[:, :, 0]
    print(f"[pure] wrote {args.out}: {lib.num_clips} clips x {lib.num_steps} steps, "
          f"y_des {tuple(yy.shape)} finite={bool(torch.isfinite(yy).all())}")
    print(f"[pure] commanded vx {tv.min():.2f} .. {tv.max():.2f} m/s over "
          f"{len({int(t) for t in np.asarray(lib.terrain_id)})} tiles")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
