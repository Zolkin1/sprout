"""Stage 1' (Motion Bricks env): drive Motion Bricks with OUR optimized strides as the target pose.

Phase-2 FLAT generation. Unlike ``mb_generate.py`` (which lets Motion Bricks free-run its built-in style
clips), this drives the model from a scripted ``(vx, vy, wz)`` command schedule and, at every replan,
supplies the *target pose* from our velocity-matched optimized steady stride (the stride bank written by
``export_stride_bank.py``) instead of Motion Bricks' style-clip holder. Motion Bricks' own spring-model
root/heading realignment is kept -- so the ROOT trajectory (where the robot goes) is Motion Bricks'
natural, physically-plausible motion toward the command, while the POSE (how the limbs move) is our
traj-opt stride. Commanded velocity -> our optimized motion at steady state; Motion Bricks in-betweens
the transitions.

The agent setup (target-pose override, exact-velocity root pin, regime-gated predict) is the shared
Stage-1 harness :mod:`mb_env`; the TERRAIN approach / exit segments are generated by
``mb_terrain_segments.py`` with the same harness, so flat and terrain differ only in what the target pose
is pinned to.

Output is the SAME ``RawMotion`` ``.npz`` contract as ``mb_generate.py``, so Stage 2
(``generate_mb_clips.py``) ingests it unchanged -- carrying BOTH command channels (the continuous
commanded velocity and the bank-snapped one the motion was generated at), so Stage 2 chooses what the RL
sees. ``--n-clips`` is LIBRARY mode: schedules are sampled from the same distribution as the DP flat
family instead of the fixed demo set. Runs in the ``motionbricks`` conda env::

    # library: 3000 sampled 9 s clips
    conda run -n motionbricks python scripts/rsl_rl/mb_encode.py \
        --mb-root ../GR00T-WholeBodyControl/motionbricks \
        --stride-bank mb_raw/stride_bank_v2.npz --out-dir mb_raw/flat_lib_v1 \
        --n-clips 3000 --clip-length 9.0 --seed 0
    # the 6 fixed demo schedules (reproducible eyeballing)
    conda run -n motionbricks python scripts/rsl_rl/mb_encode.py ... --schedule-set demo
"""

from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mb_env  # noqa: E402
from motion_gen.command_schedule import sample_command_schedule  # noqa: E402

# Historical flat-family shape, kept explicit now that the sampler is shared: a clean
# standing lead-in so every clip starts settled, and a 12% chance a segment is a pause.
_LEAD_IN_S = 1.0
_STAND_FRAC = 0.12


def sample_schedule(rng: np.random.Generator, args) -> list[tuple]:
    """One randomized ``[(duration_s, vx, vy, wz), ...]`` schedule for a clip of ``args.clip_length``.

    Delegates to :func:`motion_gen.command_schedule.sample_command_schedule`, the ONE sampler every
    clip family uses. The flat family passes the full command space -- forward / backward / sidestep
    / turn / diagonal, a standing lead-in and pauses -- and nothing overrides the result, so the
    generated motion tracks this schedule end to end. The terrain families call the same function
    with forward-only bands and let the terrain override it near the interaction.

    Velocity is what MB is COMMANDED; the target pose is snapped to the nearest bank stride, so the
    achieved steady velocity is the snapped one (see ``--rl-vels`` on the Stage-2 side).
    """
    return sample_command_schedule(
        rng, duration=float(args.clip_length), seg_dur_range=tuple(args.seg_dur_range),
        vx_range=tuple(args.walk_vx_range), run_vx_range=tuple(args.run_vx_range),
        back_vx_range=tuple(args.back_vx_range), side_vy=float(args.side_vy),
        turn_max=float(args.turn_max), stand_frac=_STAND_FRAC, lead_in_s=_LEAD_IN_S)


def _schedule_set(name: str) -> list[dict]:
    """Named sets of command schedules. Each schedule = list of (duration_s, vx, vy, wz) segments."""
    demo = [
        {"name": "stand_walk_fast_stop",
         "segs": [(1.5, 0, 0, 0), (3.0, 1.0, 0, 0), (3.0, 2.0, 0, 0), (1.5, 0, 0, 0)]},
        {"name": "walk_turn_left",
         "segs": [(1.5, 0, 0, 0), (2.5, 1.0, 0, 0), (2.5, 1.0, 0, 0.5), (2.5, 1.0, 0, 0)]},
        {"name": "walk_turn_right",
         "segs": [(1.5, 0, 0, 0), (2.5, 1.0, 0, 0), (2.5, 1.0, 0, -0.5), (2.5, 1.0, 0, 0)]},
        {"name": "speed_ramp",
         "segs": [(1.0, 0, 0, 0), (2.0, 0.5, 0, 0), (2.0, 1.5, 0, 0), (2.0, 2.5, 0, 0), (2.0, 0, 0, 0)]},
        {"name": "sidestep_left",
         "segs": [(1.5, 0, 0, 0), (3.0, 0.5, 0.4, 0), (3.0, 1.0, 0, 0), (1.5, 0, 0, 0)]},
        {"name": "stand_slowwalk_stand",
         "segs": [(2.0, 0, 0, 0), (4.0, 0.5, 0, 0), (3.0, 0, 0, 0)]},
    ]
    sets = {"demo": demo}
    if name not in sets:
        raise SystemExit(f"unknown --schedule-set {name}; have {list(sets)}")
    return sets[name]


def _generate_clip(mb: mb_env.MBAgent, targeter: mb_env.StrideTargeter, segs: list[tuple], seed: int):
    """Roll out one scripted clip with exact-velocity keyframe pinning.

    Per replan: (1) SNAP the commanded velocity to the nearest library ``steady_vel``; (2) place the target
    root at the exact-velocity rollout position (:func:`mb_env.walk_control` -> MB pins it); (3) supply the
    matched stride as the target pose, relaxed through transitions by the regime gate.

    Returns ``(qpos[T,36], cmd_raw[T,3], cmd_snapped[T,3], kf_t, kf_qpos)`` -- BOTH command channels. The
    motion is generated at ``cmd_snapped`` (the bank is discrete), while ``cmd_raw`` is the continuous
    command that was asked for; Stage 2 picks which one the RL sees (``--rl-vels``) and reports the gap.
    """
    mb.reset(seed)
    targeter.reset_phase()                                    # gait phase is per-clip, not per stride index
    total_s = sum(d for d, *_ in segs)
    n_steps = max(2, int(round(total_s * mb.fps)))
    bounds = mb_env.schedule_bounds(segs)
    qpos_stream, raw_stream, snap_stream = [], [], []
    for step in range(n_steps):
        t_now = step * mb.dt
        cmd_raw = mb_env.cmd_at(segs, t_now)                  # original commanded (non-snapped) velocity
        stride_idx = targeter.nearest(cmd_raw)                # nearest library stride
        cmd = targeter.steady_vel[stride_idx].astype(np.float32).copy()  # SNAPPED (== stride steady_vel)
        mb.set_regime(mb_env.regime_weight(bounds, t_now), t_now)
        mb.set_target_pose(targeter.window(stride_idx, advance=1))

        qpos = mb.next_frame()
        mb.step(mb_env.walk_control(mb.context(), cmd, mb.lookahead_times))
        qpos_stream.append(qpos)
        raw_stream.append(np.asarray(cmd_raw, dtype=np.float32).copy())
        snap_stream.append(cmd)
    # The third element is the per-keyframe KIND ("stride" / "terrain"); a flat clip only ever pins stride
    # targets, so there is nothing to distinguish and the sidecar stays (t, qpos) as its consumers expect.
    kf_t, kf_qpos, _kf_kind = mb.captured_keyframes()
    return (np.stack(qpos_stream, 0), np.stack(raw_stream, 0), np.stack(snap_stream, 0), kf_t, kf_qpos)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--mb-root", required=True, help="GR00T motionbricks package root.")
    p.add_argument("--stride-bank", required=True, help="Stride bank .npz (export_stride_bank.py, at MB fps).")
    p.add_argument("--out-dir", required=True, help="Directory to write RawMotion .npz files (one per clip).")
    p.add_argument("--schedules", default=None,
                   help="JSON list of {name, segs:[[dur,vx,vy,wz],...]} -- generate exactly these clips, "
                        "named by their 'name'. Used by the distractor family, whose command profiles are "
                        "authored on the env_isaaclab side (motionbricks.distractor_plan).")
    p.add_argument("--n-clips", type=int, default=None,
                   help="Generate N clips from RANDOMLY SAMPLED command schedules (library mode). Overrides "
                        "--schedule-set / --steady-vx; the schedule distribution mirrors the DP flat family.")
    p.add_argument("--clip-length", type=float, default=20.0,
                   help="Sampled-schedule clip duration (s); should match the Stage-2 --clip-length. "
                        "20 s is what the shipped libraries were built at (g1_mb_v5 carries "
                        "clip_length_s=20.0, every flat clip 999 steps); the old 9.0 default was "
                        "stale and never used for one.")
    p.add_argument("--schedule-set", default="demo", help="Named command-schedule set.")
    p.add_argument("--seg-dur-range", type=float, nargs=2, default=(1.5, 5.5),
                   metavar=("MIN", "MAX"),
                   help="Duration band (s) of one command segment in a sampled schedule. Longer "
                        "segments mean fewer command changes per clip but more settled time at each.")
    # Velocity envelope of the sampled schedules. Expressed as explicit (min, max) BANDS rather than
    # the old scale-times-fraction form: the fractions made the reachable range implicit (forward was
    # U(0.45,1)*2.5 -> [1.125, 2.5] with a hole below it) and there was no way to set a floor.
    # The walk and run bands are contiguous by default, so forward speed covers [0.1, 3.0] with no gap
    # while keeping the 60/40 walk/run weighting.
    p.add_argument("--walk-vx-range", type=float, nargs=2, default=(0.1, 1.0), metavar=("MIN", "MAX"),
                   help="Forward WALK band (m/s); also the base band for turn/diagonal segments.")
    p.add_argument("--run-vx-range", type=float, nargs=2, default=(1.0, 3.0), metavar=("MIN", "MAX"),
                   help="Forward RUN band (m/s), used on the 40%% of forward segments that run.")
    p.add_argument("--back-vx-range", type=float, nargs=2, default=(0.1, 1.5), metavar=("MIN", "MAX"),
                   help="Backward SPEED band (m/s), magnitudes; emitted as negative vx.")
    p.add_argument("--side-vy", type=float, default=1.0, help="Lateral (sidestep) speed scale (m/s).")
    p.add_argument("--turn-max", type=float, default=0.8, help="Yaw-rate scale (rad/s).")
    p.add_argument("--steady-vx", type=float, default=None,
                   help="If set, ignore --schedule-set and emit ONE steady forward-walk clip at this vx "
                        "(m/s), e.g. a flat baseline matched to a terrain traversal speed.")
    p.add_argument("--steady-secs", type=float, default=6.0, help="Duration (s) of the --steady-vx clip.")
    p.add_argument("--repeats", type=int, default=1, help="Generate each schedule this many times (varied seed).")
    p.add_argument("--bank-dt", type=float, default=None,
                   help="DIAGNOSTIC: override the stride bank's own sampling period (s) when advancing the "
                        "target-pose phase. The bank records its dt and that is what should be used; setting "
                        "this to the MB frame period (1/30) reproduces the pre-fix behaviour, where the pinned "
                        "pose walked the stride one BANK frame per MB frame -- 0.6x the cadence the root was "
                        "driven at. Only useful for measuring what that cost.")
    p.add_argument("--seed", type=int, default=1234)
    p.add_argument("--controller", default="random")          # unused; keeps build_demo_args happy
    p.add_argument("--allowed-mode", default=None)
    args = p.parse_args()

    # Every path argument must be listed: the harness resolves these BEFORE it chdirs into the Motion
    # Bricks root, so anything left out is looked up relative to that root instead of the repo.
    mb_env.enter_mb_root(args, ("stride_bank", "out_dir", "schedules"))
    raw_schema = mb_env.load_schema_module("raw_schema")
    os.makedirs(args.out_dir, exist_ok=True)
    strides, steady_vel, bank_meta = mb_env.load_bank(args.stride_bank)
    print(f"[mb_encode] bank: {len(strides)} strides, dt={bank_meta.get('dt')}, "
          f"joint_order={bank_meta.get('joint_order')}")
    # Bank COVERAGE: the reachable command set. Every commanded velocity is snapped to one of these, so
    # this is the hard ceiling on the library's velocity distribution regardless of what we command.
    bmin, bmax = steady_vel.min(axis=0), steady_vel.max(axis=0)
    print(f"[mb_encode] bank coverage: vx[{bmin[0]:+.2f},{bmax[0]:+.2f}] vy[{bmin[1]:+.2f},{bmax[1]:+.2f}] "
          f"wz[{bmin[2]:+.2f},{bmax[2]:+.2f}]  ({len(np.unique(np.round(steady_vel[:, 0], 2)))} distinct vx)")

    mb = mb_env.MBAgent(args, capture_keyframes=True)
    # The bank is stored at the RL control period and MB generates at its own fps; the targeter needs both
    # so the pinned pose walks the stride at the cadence the root is being driven at (see StrideTargeter).
    bank_dt = float(args.bank_dt) if args.bank_dt else float(bank_meta["dt"])
    if args.bank_dt:
        print(f"[mb_encode] DIAGNOSTIC: bank dt overridden {bank_meta['dt']} -> {bank_dt} "
              f"(pose cadence {bank_dt / mb.dt:.2f}x)")
    targeter = mb_env.StrideTargeter(strides, steady_vel, mb.nfpt, bank_dt=bank_dt, mb_dt=mb.dt)
    print(f"[mb_encode] {mb.describe()}")

    # Three mutually exclusive modes: sampled library (--n-clips), one steady clip (--steady-vx), or a
    # named demo set. Sampled schedules are drawn up front so the whole run is one seed away from a repeat.
    if args.schedules:
        with open(args.schedules) as f:
            schedules = [{"name": str(s["name"]), "segs": [tuple(float(v) for v in seg) for seg in s["segs"]]}
                         for s in json.load(f)]
        print(f"[mb_encode] {len(schedules)} authored schedules from {args.schedules}")
    elif args.n_clips is not None:
        rng = np.random.default_rng(args.seed)
        schedules = [{"name": "rand", "segs": sample_schedule(rng, args)} for _ in range(args.n_clips)]
        print(f"[mb_encode] sampled {len(schedules)} schedules (clip_length={args.clip_length}s, "
              f"seg_dur={tuple(args.seg_dur_range)}s, walk_vx={tuple(args.walk_vx_range)} "
              f"run_vx={tuple(args.run_vx_range)} back_vx={tuple(args.back_vx_range)} "
              f"side_vy={args.side_vy} turn_max={args.turn_max})")
    elif args.steady_vx is not None:
        schedules = [{"name": f"steady_vx{args.steady_vx:.2f}",
                      "segs": [(args.steady_secs, args.steady_vx, 0.0, 0.0)]}]
    else:
        schedules = _schedule_set(args.schedule_set)
    clip_i = n_reused = 0
    kf_clip, kf_t, kf_qpos = [], [], []                       # accumulate pinned keyframes across clips
    snap_err: list[np.ndarray] = []                           # |raw - snapped| over every frame of every clip
    for rep in range(args.repeats):
        for sch in schedules:
            seed = (args.seed * (clip_i + 2333) * 2333) % (2 ** 32 - 1)
            # Authored schedules are looked up BY NAME by their assembler, so keep the name as the stem;
            # sampled/demo clips keep the indexed stem.
            out = os.path.join(args.out_dir, (f"{sch['name']}.npz" if args.schedules
                                              else f"mb2_{clip_i:04d}_{sch['name']}.npz"))
            # RESUME: a library's worth of flat clips is hours of GPU, so never regenerate one that is
            # already on disk. Schedules are drawn deterministically from --seed, so clip i is the same
            # clip on every run and its file name identifies it.
            if os.path.exists(out):
                n_reused += 1
                clip_i += 1
                continue
            qpos, cmd_raw, cmd_snap, ktimes, kqpos = _generate_clip(mb, targeter, sch["segs"], seed)
            motion = raw_schema.RawMotion(
                mujoco_qpos=qpos, fps=mb.fps, joint_names=list(mb_env.G1_JOINT_NAMES),
                target_vel=cmd_raw, target_vel_snapped=cmd_snap, kind="flat",
                provenance={"backend": "motionbricks", "mode": "phase2_stride_target",
                            "schedule": sch["name"], "seed": int(seed), "repeat": rep,
                            "stride_bank": os.path.abspath(args.stride_bank),
                            "mb_root": os.path.abspath(args.mb_root), "clip_index": clip_i},
            )
            raw_schema.save_raw_motion(out, motion)
            kf_clip.append(np.full(len(ktimes), clip_i, np.int32)); kf_t.append(ktimes); kf_qpos.append(kqpos)
            snap_err.append(np.abs(cmd_raw - cmd_snap))
            print(f"[mb_encode]   wrote {os.path.basename(out)}  qpos={qpos.shape} "
                  f"pelvis_z~{qpos[:, 2].mean():.3f} (min {qpos[:, 2].min():.3f})  keyframes={len(ktimes)}")
            clip_i += 1

    # SNAP ERROR: how far the commanded velocity sits from the nearest reachable stride. This is the
    # command/motion divergence the RL inherits under --rl-vels raw, so it is reported, not hidden.
    if snap_err:
        e = np.concatenate(snap_err, axis=0)
        p50, p95, emax = (np.percentile(e, 50, axis=0), np.percentile(e, 95, axis=0), e.max(axis=0))
        print(f"[mb_encode] snap error |cmd - reachable| over {e.shape[0]} frames:")
        for j, ax in enumerate(("vx", "vy", "wz")):
            print(f"[mb_encode]   {ax}: p50={p50[j]:.3f} p95={p95[j]:.3f} max={emax[j]:.3f}")

    # Sidecar of pinned target keyframes (for the viser --keyframes overlay). Order matches clip index;
    # joints are in G1_JOINT_NAMES order (MuJoCo qpos layout), so viser reindexes to the URDF by name.
    # On a RESUMED run the keyframes only exist for the clips regenerated this time, so writing it would
    # replace a complete sidecar with a partial one whose clip indices no longer line up -- keep the old one
    # (the overlay is a diagnostic; the clips themselves are unaffected).
    sidecar = os.path.join(args.out_dir, "_keyframes.npz")
    if n_reused and os.path.exists(sidecar):
        print(f"[mb_encode] {n_reused} clips reused -> keeping the existing {sidecar} "
              f"(this run only has keyframes for the {clip_i - n_reused} regenerated clips)")
        print(f"[mb_encode] done: {clip_i} clips ({n_reused} already present, reused) -> {args.out_dir}")
        return 0
    np.savez_compressed(
        sidecar,
        clip_idx=np.concatenate(kf_clip) if kf_clip else np.zeros((0,), np.int32),
        t=np.concatenate(kf_t) if kf_t else np.zeros((0,), np.float32),
        qpos=np.concatenate(kf_qpos) if kf_qpos else np.zeros((0, 36), np.float32),
        joint_names=np.array(json.dumps(list(mb_env.G1_JOINT_NAMES))),
        fps=np.array(mb.fps),
    )
    total_kf = sum(len(x) for x in kf_t)
    print(f"[mb_encode] done: {clip_i} clips ({n_reused} already present, reused) -> {args.out_dir}  ({total_kf} pinned keyframes -> {sidecar})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
