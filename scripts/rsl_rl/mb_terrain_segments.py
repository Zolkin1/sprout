def _hold_cmd(plan, side: str, which: int = 0) -> float | None:
    """The RL forward command for one HOLD of ``side`` (``"approach"`` / ``"exit"``).

    Pass A authors these; both segments are GENERATED by tracking them, which is what makes the
    command the RL later sees and the motion agree everywhere the terrain does not override.

    This replaces three helpers that between them maintained an absolute CLIP TIMELINE here in
    pass B -- ``_schedule_of`` / ``_sched_cmd`` / ``_interaction_s`` -- so that the exit's command
    could be read at ``approach_s + interaction_s``. That timeline was the bug: the replay's true
    length is 2-6 s and pass A had reserved a fixed 12 s for it, so the two halves disagreed about
    when the exit begins. A hold is addressed by WHICH hold it is, and there is no time to be wrong
    about.
    """
    holds = (getattr(plan, "meta", None) or {}).get("rl_holds")
    if not holds:
        return None
    seq = holds.get(side) or []
    return float(seq[which][1]) if which < len(seq) else None


def peak_root_speed(qpos: np.ndarray, fps: float) -> float:
    """Fastest planar root speed anywhere in a generated segment (m/s)."""
    if qpos.shape[0] < 2:
        return 0.0
    return float((np.linalg.norm(np.diff(qpos[:, :2], axis=0), axis=1) * float(fps)).max())


def speed_ceiling(v0, v1) -> float:
    """The most a sane in-betweening between ``v0`` and ``v1`` may peak at.

    ``2.0 * max(|v0|, |v1|) + 1.5``, and it is deliberately loose: this is a BLOW-UP detector, not a
    tracking metric. The separation it has to resolve was measured on the quick build and is enormous
    -- sound in-betweenings peak at up to 4.0 m/s while broken ones peak at 24-31 while travelling
    8-15 m, looping several metres out and back to cover a 2 m gap.

    A tighter ``1.3 * max + 1.0`` was tried first and rejected: it fired on an interior hop peaking at
    3.9 m/s against a 3.9 ceiling, costing a clip for 0.05 m/s of ordinary gait oscillation. A real
    pelvis accelerates and decelerates within every step -- the flat family's own exact looped replays
    reach 1.66x their commanded speed below 0.5 m/s -- so a gate set near the command cannot tell a
    brisk transient from a broken one. Set it where nothing sound has ever been, and let the
    quality metrics (``mb_qc``) judge the rest.
    """
    return 2.0 * max(abs(float(v0)), abs(float(v1))) + 1.5


def _side_plan(plan, side: str):
    """The ``flat_plan.FlatClipPlan`` for one side, or ``None`` on a single-hold plan.

    Pass A authors it: a loop per commanded speed, an in-betweening between consecutive speeds. Pass B
    generates those in-betweenings and reads the terminal loop's stride and gait phase, which is the
    one thing the two passes MUST agree on -- pass B used to choose both itself, and with several
    loops on a side the last one has to hand off at exactly the stride and phase the terrain transient
    is seeded from.
    """
    d = (getattr(plan, "meta", None) or {}).get(f"{side}_plan")
    return None if not d else mb_env.load_schema_module("flat_plan").plan_from_dict(d)


def _terminal_loop(plan, side: str):
    """The loop that ADJOINS the terrain: the approach's last, the exit's first. ``None`` if absent."""
    sp = _side_plan(plan, side)
    if sp is None:
        return None
    loops = [pc for pc in sp.pieces if pc.kind == "loop"]
    if not loops:
        return None
    return loops[-1] if side == "approach" else loops[0]


def _generate_approach_bounded(mb, targeter, plan, *, pin_future: bool, a_max: float, alpha_max: float,
                               token_floor: int = 0, token_band=None, free_root: bool = False,
                               floor_s: float, slack: float, seed: int):
    """The approach as a BOUNDED transient: an exact steady stride hands off to a short in-betweening.

    The old approach was one long run-up sized by a commanded DURATION, and it did not track its command --
    measured on jump_on, an exit commanded 0.67 m/s averaged 1.19 and overran its platform by 2x.  The
    replacement splits the job the way the flat path does: an exact looped stride covers the distance
    (pass C prepends it, at exactly the commanded speed by construction) and Motion Bricks only fills the
    last stretch, where the gait actually has to change to meet the terrain.

    So this generates only that stretch: context-seeded from the stride pass C will replay, pose-pinned to
    the terrain entry, with the horizon bounded by how much velocity has to change (``mb_env.hop_tokens``)
    rather than by a duration nobody can hold the model to.

    Returns ``(qpos[T,36], cmd[T,3], info)`` where ``info`` carries the seed stride + phase so pass C can
    replay the SAME stride and hand off at the SAME gait phase.
    """
    sb = mb_env.load_schema_module("stride_bank")
    flat_plan = mb_env.load_schema_module("flat_plan")
    step = mb.dt / targeter.bank_dt
    # Seed from the SCHEDULED command, not ``plan.approach_vx``.  The clip's RL-visible ``target_vel``
    # comes from the per-clip schedule pass A authored, and both segments are generated by tracking it --
    # that agreement is the whole point of authoring it up front.  ``approach_vx`` is a different
    # quantity (the tile's nominal run-up speed), so seeding the loop from it makes the exact steady
    # stretch run at a speed the command never asks for: measured 1.99 m/s of motion against a 2.88 m/s
    # command on one clip, i.e. the loop was exact but exactly WRONG.
    # ONE command for the whole approach: its FIRST hold. Pass A emits a single hold per side for
    # now, so this is the whole approach's command rather than just its opening -- a single exact
    # loop can only express one speed. Several holds per side is the next step, and it needs the
    # approach built as a piece LIST here rather than one loop + one transient.
    # The LAST approach hold -- the one this transient departs from. With several holds the earlier
    # ones are ordinary flat stretches that have already happened.
    v_app = _hold_cmd(plan, "approach", -1)
    v_app = float(plan.approach_vx) if v_app is None else v_app
    v0 = np.array([float(v_app), 0.0, 0.0], np.float32)
    v1 = np.array([float(plan.entry_vx), 0.0, 0.0], np.float32)
    # The stride and hand-off phase come from the PLAN where pass A authored one. Choosing them here
    # (``targeter.nearest(v0)`` and ``seed % period``) worked only while the approach was a single
    # loop that pass C rebuilt from this segment's own provenance; with a loop/transient alternation
    # the last loop is authored in pass A and this must match it, and two independent 'nearest'
    # implementations agreeing is not something to rely on when they need not both exist.
    _loop = _terminal_loop(plan, "approach")
    if _loop is not None:
        s_idx, period = int(_loop.stride), int(targeter.periods[int(_loop.stride)])
        phase_out = int(_loop.phase_out) % period
    else:
        s_idx = targeter.nearest(v0)
        period = int(targeter.periods[s_idx])
        phase_out = int(seed % period)             # which gait phase the loop hands off at; pass C matches
    ctx = sb.phase_window(targeter.strides[s_idx],
                          flat_plan.transient_context_phase(phase_out, mb.nfpt, step), mb.nfpt, step)

    mb.reset(seed)
    # The horizon is Motion Bricks' OWN choice, bounded only by what the velocity change needs -- the
    # transition takes as long as it naturally takes, and the exact loop before it covers whatever is
    # left of the travel budget at a constant commanded speed.
    #
    # This used to carry a ``min_travel_m = APPROACH_ZONE_M`` floor, forcing the transient to SPAN the
    # 2 m zone. That was wrong, and measurably so at the slow end: a clip commanded 0.2 m/s entering a
    # 0.30 m/s stair traversal has |dv| = 0.1 m/s and nothing to transition, so covering 2 m meant
    # 1.87 s of coasting against a pinned pose -- exactly the "extra frames are spent coasting rather
    # than ramping" failure ``slack`` exists to prevent. It also drove EVERY approach to the 16-token
    # ceiling, which is why the latch then read as 1.87 s x speed.
    #
    # The zone is a PLANNING quantity, not a transient length: pass A reserves it beside the terrain
    # (mb_plan_library) and the clutter pass vetoes decoys inside it (terrain/clutter.py). Where the
    # deceleration genuinely needs more than one horizon -- 3.5 -> 0.1 m/s wants 2.21 s against a
    # 1.867 s ceiling -- the answer is to shed the speed on the FLAT first, through the lead-up's
    # ordinary loop/transient alternation, and let this transient bridge only what is left.
    n_min, n_max, _t_min = mb_env.hop_tokens(mb, v0, v1, a_max=a_max, alpha_max=alpha_max,
                                             floor_s=floor_s, slack=slack)
    # ``token_floor`` raises the BOTTOM of the band on a retry. See ``_emit_segment``: the pose-pinned
    # generation diverges when it takes the fewest tokens it is allowed, and the same request comes
    # out clean given more.
    n_min = int(min(mb.max_tokens, n_min + max(0, int(token_floor))))
    n_max = int(max(n_min, n_max))
    n_min, n_max = _apply_band_override(mb, n_min, n_max, token_band)
    allowed = mb_env.allowed_tokens_mask(n_min, mb.min_tokens, mb.max_tokens, n_max=n_max)
    # Pin the terrain boundary as the target POSE.  Every family now tracks the replay's future joints,
    # so the arrival keeps stepping; ``terrain_families.pin_future`` survives as the narrower question of
    # whether the root may follow that future in Z.  A descent (or a jump-on) says no -- its future is off
    # the surface it still stands on -- and gets ``hold_z``, which freezes the height without freezing the
    # gait.  The old ``hold`` froze both, and that cost half the arrival speed (see approach_pin_window).
    pin_win = plan.approach_pin_window(0.0, mb.nfpt, mb.dt, hold_z=not pin_future)
    seed_ctx = t.as_tensor(np.asarray(ctx, np.float32), dtype=t.float32, device=mb.agent._device)[None]
    cx, cy, _cz, cyaw = mb_env.cur_pose(seed_ctx)

    # WHERE the entry is: only as far ahead as this bounded stretch can actually travel, since the loop
    # covers the rest.  Mean of the two speeds over the kept duration -- the transient is the deceleration.
    #
    # The duration has to be the one MB ACTUALLY picks, which is only known after priming.  Sizing the
    # carrot from ``n_min`` while the model helps itself to more tokens hands it a target it reaches
    # early, so it coasts the rest of the horizon: measured over the segment bank, arrival speed fell
    # from 0.50x the replay's entry speed at the minimum 6 tokens to 0.25x at 11-14, corr -0.57.  So
    # prime, re-size from the horizon that came back, and re-prime until the choice stops moving.
    def _carrot(n_frames: int) -> tuple[float, float, float]:
        kept_s = (n_frames - 2 * mb.nfpt) / mb.fps
        d = 0.5 * (abs(float(v_app)) + abs(float(plan.entry_vx))) * max(kept_s, 1e-3)
        return (cx + math.cos(cyaw) * d, cy + math.sin(cyaw) * d, cyaw)

    n = int(n_min * mb.nfpt)
    for _ in range(3):
        # Re-pin after every reset: set_target_pose / set_regime write onto the wrapped MB agent, and
        # mb.reset() calls that agent's own reset -- so priming without re-setting them would silently
        # generate the retry with no boundary pin at all.
        mb.reset(seed)
        mb.set_target_pose(pin_win, kind="terrain")
        mb.set_regime(1.0, 0.0)
        n_new = int(mb.prime(mb_env.walk_control(seed_ctx, v1, mb.lookahead_times, target=None if free_root else _carrot(n),
                                                 allowed_tokens=allowed, free_root=free_root)))
        if n_new == n:
            break
        n = n_new
    frames = np.stack([mb.next_frame() for _ in range(int(n))], 0)

    lead = _seed_overlap_idx(frames, np.asarray(ctx[-1], np.float32)) + 1
    end = frames.shape[0] - mb.nfpt      # the target window's first frame IS the replay's entry frame
    if end - lead < 2:
        raise RuntimeError(f"bounded approach: horizon {n} leaves {end - lead} frames after trimming")
    qpos = frames[lead:end]
    cmd = np.tile(v1, (qpos.shape[0], 1))
    travel = float(np.linalg.norm(qpos[-1, :2] - qpos[0, :2]))
    # n_min / n_max / t_min are recorded because the LATCH DISTANCE (``travel``) is the number this
    # stage is judged on, and without them a latch that is too long is indistinguishable between "the
    # deceleration physically needs that far" and "the token band never bound the model".
    return qpos, cmd, {"seed_stride": int(s_idx), "seed_phase": int(phase_out),
                       "sched_vx": float(v_app), "entry_vx": float(plan.entry_vx),
                       "n_min": int(n_min), "n_max": int(n_max), "t_min": float(_t_min),
                       # The CEILING, recorded because the band is meaningless without it:
                       # n_min == n_max says the model had no choice, but only max_tokens says
                       # whether that was the ceiling biting or the slack never asking.
                       "max_tokens": int(mb.max_tokens), "nfpt": int(mb.nfpt),
                       "tokens": int(n) // mb.nfpt, "travel": travel, "bounded": True}


def _seed_overlap_idx(frames: np.ndarray, seed_last: np.ndarray, search: int = 8) -> int:
    """Last leading frame that still replays the context seed (Motion Bricks re-predicts it first)."""
    k = min(search, frames.shape[0] - 1)
    if k < 1:
        return 0
    return int(np.argmin(np.linalg.norm(frames[:k, 7:] - seed_last[None, 7:], axis=1)))



def _generate_exit_bounded(mb, targeter, plan, *, a_max: float, alpha_max: float,
                           token_floor: int = 0, token_band=None, free_root: bool = False, floor_s: float,
                           slack: float, seed: int):
    """The exit as a BOUNDED transient: the replay hands off to a short in-betweening, then an exact loop.

    The mirror of :func:`_generate_approach_bounded`, and the one that fixes the defect that started this:
    the old duration-driven exit did not track its command -- commanded 0.67 m/s it averaged 1.19 and
    travelled 6.5 m across a 4.7 m platform, which walked 41% of ``jump_on`` off the box top.  Bounding the
    transient and letting an exact looped stride cover the rest makes the travel ``command x duration`` by
    construction, so the platform sizing is correct instead of optimistic.

    Motion Bricks' height prior is ABSOLUTE (it generates for a floor at z = 0), so the seed is lowered by
    the exit surface: seeding it 0.45 m up on a box makes the walk-away sink back to its ~0.78 m pelvis
    height, i.e. through the platform.  The splice grounds it back afterwards.

    Returns ``(qpos[T,36], cmd[T,3], info)`` with the loop stride + entry phase for pass C.
    """
    sb = mb_env.load_schema_module("stride_bank")
    step = mb.dt / targeter.bank_dt
    # ONE command for the whole exit (pass A holds the schedule constant across it).
    # The exit's FIRST hold. No clip timeline is consulted: this used to be read at
    # ``approach_s + _interaction_s(plan)`` on a schedule pass A had laid out assuming a fixed 12 s
    # interaction, against a replay that is really 2-6 s.
    v_ex = _hold_cmd(plan, "exit")
    v_ex = float(plan.exit_vx) if v_ex is None else v_ex
    v0 = np.array([float(plan.exit_speed), 0.0, 0.0], np.float32)     # the replay's speed at hand-off
    v1 = np.array([float(v_ex), 0.0, 0.0], np.float32)
    _loop = _terminal_loop(plan, "exit")
    if _loop is not None:                      # authored in pass A; see _generate_approach_bounded
        s_idx, period = int(_loop.stride), int(targeter.periods[int(_loop.stride)])
        phase_in = int(_loop.phase0) % period
    else:
        s_idx = targeter.nearest(v1)
        period = int(targeter.periods[s_idx])
        phase_in = int(seed % period)          # gait phase the loop is ENTERED at; pass C matches it
    target = sb.phase_window(targeter.strides[s_idx], phase_in, mb.nfpt, step)

    mb.reset(seed)
    mb.set_target_pose(target, kind="stride")
    mb.set_regime(1.0, 0.0)
    n_min, n_max, _t = mb_env.hop_tokens(mb, v0, v1, a_max=a_max, alpha_max=alpha_max,
                                         floor_s=floor_s, slack=slack)
    n_min = int(min(mb.max_tokens, n_min + max(0, int(token_floor))))
    n_max = int(max(n_min, n_max))
    n_min, n_max = _apply_band_override(mb, n_min, n_max, token_band)
    allowed = mb_env.allowed_tokens_mask(n_min, mb.min_tokens, mb.max_tokens, n_max=n_max)
    win = plan.exit_seed_window(mb.nfpt, mb.dt)
    win[:, 2] -= float(plan.exit_surf_z)                              # generate on virtual flat ground
    seed_ctx = t.as_tensor(np.asarray(win, np.float32), dtype=t.float32, device=mb.agent._device)[None]
    # The exit never had a fixed CARROT -- it takes walk_control's velocity rollout -- so
    # `free_root` here means dropping that rollout pin, not a carrot. Same meaning as the
    # approach (no positional pin at all), different thing being removed.
    n = mb.prime(mb_env.walk_control(seed_ctx, v1, mb.lookahead_times, allowed_tokens=allowed,
                                     free_root=free_root))
    frames = np.stack([mb.next_frame() for _ in range(int(n))], 0)

    lead = _seed_overlap_idx(frames, np.asarray(win[-1], np.float32)) + 1
    end = frames.shape[0] - mb.nfpt          # the target window's first frame is the loop's phase_in
    if end - lead < 2:
        raise RuntimeError(f"bounded exit: horizon {n} leaves {end - lead} frames after trimming")
    qpos = frames[lead:end]
    cmd = np.tile(v1, (qpos.shape[0], 1))
    travel = float(np.linalg.norm(qpos[-1, :2] - qpos[0, :2]))
    return qpos, cmd, {"loop_stride": int(s_idx), "loop_phase": int(phase_in), "sched_vx": float(v_ex),
                       "tokens": int(n) // mb.nfpt, "travel": travel, "bounded": True}


def _emit_interior(mb, targeter, plan, side: str, piece_key: str, out: str, args, raw_schema) -> str:
    """Generate ONE interior lead-up / trail-away transient and write it as a ``RawMotion``.

    This is an ORDINARY loop-to-loop in-betweening -- the same job the flat family's transients are --
    so it goes through the SAME generator (``mb_transient.generate``). That matters beyond tidiness:
    the shared one chains multiple hops through velocity waypoints for a large change, which is the
    difference between 1.70 and 5.08 m/s^2 of peak acceleration, and the terrain driver's own
    single-hop generators do not.
    """
    sb = mb_env.load_schema_module("stride_bank")
    flat_plan = mb_env.load_schema_module("flat_plan")
    sp = _side_plan(plan, side)
    if sp is None:
        raise RuntimeError(f"{piece_key}: plan carries no {side}_plan")
    tr = next((pc for pc in sp.pieces if pc.kind == "transient" and pc.key == piece_key), None)
    if tr is None:
        raise RuntimeError(f"{piece_key}: not a transient of the {side} plan")
    a_max = float(args.flat_a_max if args.flat_a_max is not None else args.a_max)
    ceil_ = speed_ceiling(targeter.steady_vel[tr.stride_out][0] if tr.stride_out >= 0 else 0.0,
                          targeter.steady_vel[tr.stride_in][0])
    # Keyed off the piece name so two transients of one clip get different streams, and off the
    # attempt so a diverged draw is not simply repeated. ``hash`` is per-process randomized, which
    # would make a rebuild irreproducible, so the key is folded deterministically instead.
    base = sum((i + 1) * ord(ch) for i, ch in enumerate(piece_key))
    qpos = None
    for attempt in range(max(1, int(args.gen_attempts))):
        qpos, diag = mb_transient.generate(
            mb, sb, flat_plan, targeter.strides, targeter.steady_vel, targeter.bank_dt, tr,
            seed=(args.seed * 2654435761 + base * 1000003 + attempt * 7919) % (2 ** 31),
            a_max=a_max, alpha_max=args.alpha_max, floor_s=args.min_transient_s,
            ramp_dv=args.ramp_dv, slack=args.hop_slack)
        pk = peak_root_speed(qpos, mb.fps)
        diag["peak_speed"], diag["speed_ceiling"], diag["attempts"] = float(pk), float(ceil_), attempt + 1
        if pk <= ceil_:
            break
        print(f"[mb_seg][retry] {piece_key} interior: peak {pk:.1f} m/s over a {ceil_:.1f} ceiling "
              f"(attempt {attempt + 1})", flush=True)
    else:
        raise RuntimeError(f"{piece_key}: interior in-betweening diverged on every seed "
                           f"(peak {peak_root_speed(qpos, mb.fps):.1f} m/s > {ceil_:.1f})")
    tvel = np.tile(np.asarray(diag["cmd"], np.float32), (qpos.shape[0], 1))
    motion = raw_schema.RawMotion(
        mujoco_qpos=qpos.astype(np.float32), fps=mb.fps, joint_names=list(mb_env.G1_JOINT_NAMES),
        target_vel=tvel, kind="terrain_interior",
        provenance={"backend": "motionbricks", "mode": f"{side}_interior", "skill": plan.skill,
                    "key": piece_key, "stride_out": int(tr.stride_out), "phase_out": int(tr.phase_out),
                    "stride_in": int(tr.stride_in), "phase_in": int(tr.phase_in),
                    "gen_version": _GEN_VERSION,
                    "stride_bank": os.path.basename(args.stride_bank),
                    "a_max": float(a_max), "alpha_max": float(args.alpha_max),
                    "min_transient_s": float(args.min_transient_s),
                    "hop_slack": float(args.hop_slack), "ramp_dv": float(args.ramp_dv),
                    **diag})
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    raw_schema.save_raw_motion(out, motion)
    return out


def _cli_band(args):
    """``--token-band LO HI`` as a ``(lo, hi)`` pair, with -1 meaning "leave that end derived"."""
    b = getattr(args, "token_band", None)
    if not b:
        return None
    lo, hi = int(b[0]), int(b[1])
    return (None if lo < 0 else lo, None if hi < 0 else hi)


def _apply_band_override(mb, n_min: int, n_max: int, band) -> tuple[int, int]:
    """Apply a caller-supplied token band, clipped to what Motion Bricks can actually emit.

    ``band`` is ``(lo, hi)``; either may be ``None`` to leave that end alone, and ``lo == hi`` forces
    one horizon exactly. Only ``stitch_lab`` and ``--token-band`` set it -- a library build passes
    ``None`` and gets the derived band unchanged, so this cannot move a build by accident.

    It exists because the derived band routinely COLLAPSES: `hop_tokens` sizes the transient from the
    velocity change alone, so a hand-off that barely changes speed gets `n_min == n_max` and Motion
    Bricks' own horizon head -- which chooses 6..16 tokens -- is masked down to a single option. That
    is fine when the transient only has to change speed and wrong when it also has to reconcile a
    gait phase, which needs about half a cycle it cannot ask for.
    """
    if not band:
        return n_min, n_max
    lo, hi = band
    if lo is not None:
        n_min = int(np.clip(int(lo), mb.min_tokens, mb.max_tokens))
    if hi is not None:
        n_max = int(np.clip(int(hi), mb.min_tokens, mb.max_tokens))
    return n_min, int(max(n_min, n_max))


def _emit_segment(mb, targeter, plan, family, side: str, pin: str, dist: float, out: str,
                  args, raw_schema, quiet: bool = False, plan_path: str | None = None,
                  start: str = "stand") -> str:
    """Generate ONE segment (``side`` of ``plan``) and write it as a ``RawMotion``; returns the path."""
    seed0 = (args.seed * (1 + (side == "exit")) * 2333) % (2 ** 32 - 1)
    extra: dict = {}
    # BOUNDED is the only path. An exact looped stride covers the travel budget and Motion Bricks
    # only bridges the last stretch, so a segment is [exact loop][transient] on either side.
    #
    # There used to be a second, unbounded pair of generators here, selected by --bounded-approach
    # plus a per-plan mode/distance test. They were DEAD on every driver run and had been for some
    # time: every family in FAMILIES is approach_mode == exit_mode == "walk", approach_dist and
    # exit_dist are both positive by construction (duration x speed), --exit-pin defaults to "hard",
    # and both shipped recipes set bounded_approach: true. So the guards always passed and the
    # legacy arms were unreachable -- which means --ramp-s, --pin-cmd, --pin-lead, --pin-tail,
    # --pin-place and --pin-dist did NOTHING, including the recipe's `pin_cmd: ramp`. The measured
    # -6.8 -> -2.7 m/s^2 entry-deceleration improvement that knob is credited with came from the
    # bounded rewrite itself, not from the knob. Deleting them is what makes the recipe's central
    # claim -- that a stated parameter is a parameter that acts -- true again.
    # GENERATE, CHECK, RETRY ON THE HORIZON. The pose-pinned terrain generation diverges when it takes
    # the FEWEST tokens it is allowed: measured on the quick build, a 2.60 -> 0.36 m/s request peaked at
    # 30.6 m/s at 11 tokens and 3.0 at 13, and a 2.91 -> 0.10 peaked at 24.0 at 13 and 4.0 at 16 --
    # identical endpoints, opposite outcomes, the horizon the only difference. So each attempt raises
    # the floor of the allowed band by one token.
    #
    # A SEEDED retry was tried first and does nothing: three attempts on the same request returned
    # "peak 24.7 m/s" three times, bit-identical. Motion Bricks is deterministic given the same context
    # and target, so ``mb.reset(seed)`` moves no sampling that matters here. The seed still varies per
    # attempt (it costs nothing and the flat path does sample), but the horizon is what actually works.
    v_hi = (_hold_cmd(plan, "approach", -1) if side == "approach" else _hold_cmd(plan, "exit", 0))
    v_hi = (plan.approach_vx if side == "approach" else plan.exit_vx) if v_hi is None else v_hi
    v_lo = plan.entry_vx if side == "approach" else plan.exit_speed
    ceil_ = speed_ceiling(v_hi, v_lo)
    qpos = cmd = None
    for attempt in range(max(1, int(args.gen_attempts))):
        seed = (seed0 + attempt * 2654435761) % (2 ** 32 - 1)
        if side == "approach":
            pin_future = family.pin_future if args.pin_future == "auto" else (args.pin_future == "on")
            qpos, cmd, extra = _generate_approach_bounded(
                mb, targeter, plan, pin_future=pin_future, a_max=args.a_max,
                alpha_max=args.alpha_max, floor_s=args.min_transient_s, slack=args.hop_slack,
                token_floor=attempt, token_band=_cli_band(args), free_root=bool(args.free_root), seed=seed)
        else:
            qpos, cmd, extra = _generate_exit_bounded(
                mb, targeter, plan, a_max=args.a_max, alpha_max=args.alpha_max,
                floor_s=args.min_transient_s, slack=args.hop_slack, token_floor=attempt, token_band=_cli_band(args), free_root=bool(args.free_root), seed=seed)
        pk = peak_root_speed(qpos, mb.fps)
        extra["peak_speed"] = float(pk)
        extra["speed_ceiling"] = float(ceil_)
        extra["attempts"] = attempt + 1
        if pk <= ceil_:
            break
        print(f"[mb_seg][retry] {plan.skill} {side}: peak {pk:.1f} m/s over a {ceil_:.1f} "
              f"ceiling at {extra.get('tokens')} tokens; raising the floor "
              f"(attempt {attempt + 1})", flush=True)
    else:
        raise RuntimeError(
            f"{plan.skill} {side}: the in-betweening diverged on every one of "
            f"{args.gen_attempts} seeds -- peak {peak_root_speed(qpos, mb.fps):.1f} m/s against a "
            f"{ceil_:.1f} m/s ceiling for a {v_hi:+.2f} -> {v_lo:+.2f} transition.")

    motion = raw_schema.RawMotion(
        mujoco_qpos=qpos, fps=mb.fps, joint_names=list(mb_env.G1_JOINT_NAMES),
        target_vel=cmd, kind="terrain",
        provenance={"backend": "motionbricks", "mode": f"terrain_{side}", "pin": pin, **extra,
                    # Every segment is generated with its walking surface at z = 0 ("flat"), so the
                    # splice grounds / welds both sides identically; ``seeded`` says whether Motion
                    # Bricks was context-seeded from the terrain (its output then opens by re-predicting
                    # the seed frames, which the splice skips).
                    # ``seeded`` is a fact about the GENERATOR, not a knob: _generate_exit_bounded
                    # always context-seeds from the terrain, so every exit re-predicts its seed
                    # frames and the splice must skip that overlap. It used to read
                    # ``side == "exit" and pin == "hard"``, which was equivalent only because the
                    # pin ALSO selected the generator. With the bounded path now unconditional,
                    # deriving it from the pin would let --exit-pin soft produce a seeded exit
                    # labelled unseeded -- the splice would then keep the re-predicted frames and
                    # the exit would open by replaying the terrain's last stride.
                    "frame": "flat", "seeded": bool(side == "exit"),
                    "start": start if side == "approach" else "",
                    "skill": plan.skill, "seed": int(seed),
                    "plan": os.path.abspath(plan_path) if plan_path else "",
                    # The full set of knobs that shape this motion -- ``_gen_params`` compares them on
                    # resume so a settings change regenerates instead of silently reusing a stale segment
                    # (they are NOT in the request key, which only describes WHAT to reach, not HOW).
                    "gen_version": _GEN_VERSION,
                    "a_max": float(args.a_max),
                    "alpha_max": float(args.alpha_max),
                    "min_transient_s": float(args.min_transient_s), "hop_slack": float(args.hop_slack),
                    "dist": dist, "pin_future": args.pin_future,
                    # BASENAME, because that is what ``_gen_params`` compares -- the driver absolutizes the
                    # path, so comparing the full one would mark every segment stale after a work-dir move.
                    # The resolved path is kept alongside for provenance only.
                    "stride_bank": os.path.basename(args.stride_bank),
                    "stride_bank_path": os.path.abspath(args.stride_bank),
                    "mb_root": os.path.abspath(args.mb_root)},
    )
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    raw_schema.save_raw_motion(out, motion)
    if not quiet:
        z = qpos[:, 2]
        boundary = "last" if side == "approach" else "first"
        bz = float(z[-1] if side == "approach" else z[0])
        print(f"[mb_seg]   {side:8s} pin={pin:4s} {qpos.shape[0]}f ({dist:.2f} m budget) cmd "
              f"{cmd[0, 0]:+.2f} -> {cmd[-1, 0]:+.2f} m/s  pelvis_z {z[0]:.2f} -> {z[-1]:.2f} "
              f"({boundary} frame z={bz:.2f})  -> {os.path.basename(out)}")
    return out


# Generation knobs that change the MOTION for the same request. The key deliberately does not include
# them (it says which boundary pose to reach and at what command), so resume compares them explicitly.
_GEN_KNOBS = ("gen_version", "stride_bank", "pin_future", "start", "dist", "pin", "a_max",
              "alpha_max", "min_transient_s", "hop_slack")

# Bump when the GENERATOR changes what it produces for identical knobs -- a CLI flag is comparable, code
# is not, so without this a semantic change silently reuses every cached segment.  Compared like any other
# knob, so the invalidation is one greppable line rather than a manual ``rm -rf segments/``.
#   2: StrideTargeter walks the pinned stride at the MB frame rate (was 0.6x) and wraps on the true
#      period F-1 (was F-nfpt, skipping nfpt-1 frames per cycle).
#   3: the approach can be a BOUNDED transient seeded from an exact stride, so the same request no
#      longer describes the same motion.
#   4: (superseded)
#   6: the travel budget is a DISTANCE, so the knob the segment is keyed on changed name and unit
#      ("secs" -> "dist"); a stale dict must not compare equal to the new one.
#  12: the speed gate retries on the HORIZON (a seeded retry is a no-op -- the generator is
#      deterministic given the same context and target), and the ceiling is loosened.
#  11: every in-betweening is speed-gated with a seeded retry, and the interior ones take
#      the FLAT acceleration bound. Both change what a given request produces.
#  10: the approach transient's horizon is Motion Bricks' own choice again -- the travel
#      floor added at 7/9 forced it to span the zone, which at the slow end meant coasting
#      against a pinned pose with nothing to transition. The exact loop covers the rest.
#   9: (superseded by 10) a travel-floored hop got a token band of exactly one.
#   8: the approach segment records its token band (n_min/n_max/t_min), so a stale file
#      without them cannot be read by the latch diagnostic.
#   7: the approach transient carries a TRAVEL floor (approach_zone.APPROACH_ZONE_M), so it is
#      longer at low speed than the same request used to produce -- the whole point being that the
#      latch distance stops tracking speed.
#   5: the bounded path is the ONLY path. The unbounded generators and the --ramp-s / --pin-cmd /
#      --pin-lead / --pin-tail / --pin-place / --pin-dist knobs are gone -- they were dead on every
#      driver run, so no segment on disk was ever produced by them, but the knob set they were
#      compared against changed and a stale dict must not compare equal to the new one.
_GEN_VERSION = 12


def _gen_params(args, side: str, pin: str, dist: float, start: str) -> dict:
    """The generation knobs this run would use for one segment.

    ``stride_bank`` is compared by BASENAME: the driver absolutizes the path, so comparing the full path
    would invalidate every segment whenever the work dir moved, while the basename still catches the case
    that matters (a different bank).
    """
    return {"gen_version": _GEN_VERSION, "stride_bank": os.path.basename(args.stride_bank),
            "a_max": float(args.a_max), "alpha_max": float(args.alpha_max),
            "min_transient_s": float(args.min_transient_s), "hop_slack": float(args.hop_slack),
            "pin_future": args.pin_future, "start": start if side == "approach" else "",
            "dist": float(dist), "pin": pin}


def _is_stale(path: str, want: dict, raw_schema) -> str | None:
    """``None`` if the segment on disk was generated with ``want``; else the first differing knob.

    Without this, changing e.g. ``--pin-lead`` would leave every already-generated segment in place: the
    request key is unchanged, so resume would treat stale motion as done.
    """
    try:
        prov = dict(raw_schema.load_raw_motion(path).provenance or {})
    except Exception:
        return "unreadable"
    for k in _GEN_KNOBS:
        if k not in prov:
            return f"{k} (not recorded)"
        a, b = prov[k], want[k]
        if isinstance(b, float) and isinstance(a, (int, float)):
            if abs(float(a) - b) > 1e-9:
                return f"{k}: {a} != {b}"
        elif a != b:
            return f"{k}: {a!r} != {b!r}"
    return None


_INTERIOR_KNOBS = ("gen_version", "stride_bank", "a_max", "alpha_max", "min_transient_s",
                   "hop_slack", "ramp_dv")


def _is_stale_interior(path: str, args, raw_schema) -> str | None:
    """``None`` if the interior transient on disk was generated with today's knobs.

    A narrower key than ``_GEN_KNOBS``: an interior transient has no ``side``/``pin``/``dist``/``start``
    -- those describe a TERRAIN boundary, and this is a plain loop-to-loop hop. What it does share is
    ``gen_version``, so a change to what the generator produces invalidates both kinds together.
    """
    want = {"gen_version": _GEN_VERSION, "stride_bank": os.path.basename(args.stride_bank),
            "a_max": float(args.flat_a_max if args.flat_a_max is not None else args.a_max),
            "alpha_max": float(args.alpha_max),
            "min_transient_s": float(args.min_transient_s), "hop_slack": float(args.hop_slack),
            "ramp_dv": float(args.ramp_dv)}
    try:
        prov = dict(raw_schema.load_raw_motion(path).provenance or {})
    except Exception:
        return "unreadable"
    for k in _INTERIOR_KNOBS:
        if k not in prov:
            return f"{k} (not recorded)"
        a, b = prov[k], want[k]
        if isinstance(b, float) and isinstance(a, (int, float)):
            if abs(float(a) - b) > 1e-9:
                return f"{k}: {a} != {b}"
        elif a != b:
            return f"{k}: {a!r} != {b!r}"
    return None


def _run_batch(args, mb, targeter, raw_schema, plan_mod, families) -> int:
    """BATCH mode: generate every unique segment in ``requests.json``, in this one process.

    Each request names a representative plan + which side to generate; plans are cached because many
    requests share one. A segment whose ``.npz`` already exists is skipped, so an interrupted pass resumes,
    and a failure is recorded per request instead of taking down the run.
    """
    work = args.work_dir or os.path.dirname(os.path.abspath(args.requests))
    with open(args.requests) as f:
        reqs = json.load(f)["requests"]
    plans: dict[str, object] = {}
    done = fail = skipped = stale = 0
    print(f"[mb_seg] batch: {len(reqs)} unique segments (work-dir {work})")
    for i, r in enumerate(reqs):
        out = os.path.join(work, r["out"])
        try:
            ppath = os.path.join(work, r["plan"])
            if ppath not in plans:
                plans[ppath] = plan_mod.load_terrain_plan(ppath)
            plan = plans[ppath]
            family = families.family_for(plan.skill)
            # The TRAVEL BUDGET, which is what defines the segment now. It used to be a duration,
            # and the duration is emergent from the budget and the speed.
            if r["side"].endswith("_interior"):
                # Keyed per clip and never shared, so an existing file is either this run's or a
                # previous attempt at the same plan; the knob comparison below still applies.
                if os.path.exists(out) and _is_stale_interior(out, args, raw_schema) is None:
                    skipped += 1
                    continue
                _emit_interior(mb, targeter, plan, r["side"].rsplit("_", 1)[0], r["piece_key"],
                               out, args, raw_schema)
                done += 1
                continue
            dist = float(plan.approach_dist if r["side"] == "approach" else plan.exit_dist)
            if os.path.exists(out):
                why = _is_stale(out, _gen_params(args, r["side"], r["pin"], dist,
                                                 r.get("start", "stand")), raw_schema)
                if why is None:
                    skipped += 1
                    continue
                if stale == 0:
                    print(f"[mb_seg] regenerating: on-disk segments differ ({why})", flush=True)
                stale += 1
            _emit_segment(mb, targeter, plan, family, r["side"], r["pin"], dist, out, args,
                          raw_schema, quiet=True, plan_path=ppath, start=r.get("start", "stand"))
            done += 1
        except (Exception, SystemExit) as e:     # one bad segment costs one clip, not the library
            fail += 1
            print(f"[mb_seg][FAIL] {r['side']} {r['key'][:8]} ({r.get('plan')}): {type(e).__name__}: {e}")
        if (i + 1) % 25 == 0 or i + 1 == len(reqs):
            print(f"[mb_seg]   {i + 1}/{len(reqs)}  generated={done} reused={skipped} failed={fail}",
                  flush=True)
    print(f"[mb_seg] batch done: {done} generated ({stale} of them stale + regenerated), "
          f"{skipped} reused, {fail} FAILED")
    # A failure costs its CLIP, not the run -- pass C already skips a clip whose segment is missing.
    # The stage fails only when nothing at all came out of it, and REUSED counts: on a resume every
    # good segment is cached, so ``done`` is 0 and the handful that legitimately cannot be generated
    # would otherwise abort a build whose library is complete. Measured: with 56 cached and the 4
    # known-divergent requests failing again, the whole build stopped.
    return 1 if (fail and not done and not skipped) else 0


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--mb-root", required=True, help="GR00T motionbricks package root.")
    p.add_argument("--stride-bank", required=True, help="Flat stride bank .npz (export_stride_bank.py).")
    p.add_argument("--plan", default=None, help="Terrain plan .npz (mb_terrain_clips.py --dump-plan).")
    p.add_argument("--out-dir", default=None, help="Directory for the approach / exit RawMotion .npz files.")
    p.add_argument("--requests", default=None,
                   help="BATCH mode: requests.json from mb_plan_library.py. Generates every unique segment "
                        "the library needs in THIS process -- the whole point, since loading the model "
                        "dominates the cost of one segment. Paths inside it are relative to --work-dir.")
    p.add_argument("--work-dir", default=None,
                   help="[batch] Root the requests' plan/out paths resolve against (default: the "
                        "requests.json directory).")
    p.add_argument("--approach-pin", default="hard", choices=["hard", "soft"],
                   help="hard: in-between into the terrain entry pose (weld, no ease). "
                        "soft: free steady walk (placed + eased at splice time).")
    p.add_argument("--exit-pin", default="hard", choices=["hard", "soft"],
                   help="hard: context-seed from the terrain exit pose (weld, no ease). "
                        "soft: free steady walk (placed + eased at splice time).")
    p.add_argument("--approach-dist", type=float, default=None,
                   help="Override the plan's approach travel budget (m).")
    p.add_argument("--exit-dist", type=float, default=None,
                   help="Override the plan's exit travel budget (m).")
    p.add_argument("--pin-future", default="auto", choices=["auto", "on", "off"],
                   help="[hard approach] once the arrival is inside the planning horizon, track the replay's "
                        "own FUTURE frames (on) or hold the entry pose (off). auto = the family's own "
                        "setting (on for ascents only -- see terrain_families.pin_future for the measured "
                        "comparison).")
    p.add_argument("--approach-start", default="stand", choices=["stand", "steady"],
                   help="[single-plan] what the approach begins from: 'stand' (reset, run-up) or 'steady' "
                        "(context-seeded from the matched stride, already at the command). In batch mode "
                        "this comes per request from mb_plan_library --steady-approach-frac.")
    p.add_argument("--a-max", type=float, default=2.0,
                   help="Max planar acceleration (m/s^2) a bounded transient may demand.")
    p.add_argument("--alpha-max", type=float, default=2.0, help="Max yaw acceleration (rad/s^2).")
    p.add_argument("--min-transient-s", type=float, default=0.35,
                   help="Absolute floor on a bounded transient's kept duration (s).")
    p.add_argument("--free-root", action="store_true",
                   help="Drop the positional pin on a terrain boundary transient and let Motion "
                        "Bricks choose the root motion itself (see mb_env.walk_control free_root). "
                        "DEBUG: the driver never passes it.")
    p.add_argument("--token-band", type=int, nargs=2, default=None, metavar=("LO", "HI"),
                   help="Force the in-betweening's token band, overriding the one hop_tokens derives "
                        "from the velocity change. LO == HI pins one horizon exactly. -1 on either "
                        "end leaves that end derived. TERRAIN boundary transients only.")
    p.add_argument("--gen-attempts", type=int, default=3,
                   help="Seeds to try before giving up on one in-betweening. The pose-pinned terrain "
                        "generation occasionally diverges on a particular draw -- neighbours with "
                        "identical endpoints come out clean -- so a retry is the cheap fix. Exhausting "
                        "them costs ONE clip, loudly, instead of shipping a 30 m/s segment.")
    p.add_argument("--flat-a-max", type=float, default=None,
                   help="Acceleration bound for the INTERIOR lead-up transients, which are ordinary "
                        "loop-to-loop hops rather than terrain-boundary ones. Defaults to --a-max; the "
                        "driver passes the FLAT family's value, since it is the flat generator they "
                        "use and it is measurably cleaner there.")
    p.add_argument("--ramp-dv", type=float, default=1.0,
                   help="Max planar speed change (m/s) any ONE generation may be asked for, for the "
                        "INTERIOR lead-up / trail-away transients. A bigger change is split into "
                        "chained hops through intermediate velocity waypoints, because peak "
                        "acceleration tracks the size of the change, not the time allowed for it. "
                        "Does not apply to the two terrain-boundary transients: those are pinned to a "
                        "terrain POSE rather than to a stride, so a chain has nowhere to put its "
                        "intermediate targets. Same flag, same default, same meaning as "
                        "mb_flat_transients.")
    p.add_argument("--hop-slack", type=float, default=1.3,
                   help="How much longer than the acceleration bound requires a transient may take.")
    p.add_argument("--tag", default="", help="Suffix for the output filenames (e.g. the pin combination).")
    p.add_argument("--side", default="both", choices=["both", "approach", "exit"],
                   help="Generate only one side (e.g. to re-roll a seam without redoing the other).")
    p.add_argument("--seed", type=int, default=1234)
    p.add_argument("--controller", default="random")          # unused; keeps build_demo_args happy
    p.add_argument("--allowed-mode", default=None)
    args = p.parse_args()

    if bool(args.requests) == bool(args.plan):
        raise SystemExit("pass exactly one of --plan (single) or --requests (batch)")
    if args.plan and not args.out_dir:
        raise SystemExit("--plan needs --out-dir")

    mb_env.enter_mb_root(args, ("stride_bank", "plan", "out_dir", "requests", "work_dir"))
    raw_schema = mb_env.load_schema_module("raw_schema")
    plan_mod = mb_env.load_schema_module("terrain_plan")
    families = mb_env.load_schema_module("terrain_families")

    strides, steady_vel, bank_meta = mb_env.load_bank(args.stride_bank)
    mb = mb_env.MBAgent(args, capture_keyframes=True)
    # Bank dt and MB dt differ (RL control period vs model fps); the targeter needs both so the pinned pose
    # walks the stride at the cadence the root is driven at (see StrideTargeter).
    targeter = mb_env.StrideTargeter(strides, steady_vel, mb.nfpt,
                                     bank_dt=float(bank_meta["dt"]), mb_dt=mb.dt)
    print(f"[mb_seg] bank: {len(strides)} strides (dt={bank_meta.get('dt')});  {mb.describe()}")
    if args.requests:
        return _run_batch(args, mb, targeter, raw_schema, plan_mod, families)

    plan = plan_mod.load_terrain_plan(args.plan)
    family = families.family_for(plan.skill)
    os.makedirs(args.out_dir, exist_ok=True)
    print(f"[mb_seg] {plan.skill}: {family.blurb}")
    print(f"[mb_seg]   plan: replay {plan.replay.shape[0]}f, entry {plan.entry_frame} exit {plan.exit_frame}, "
          f"surfaces approach z={plan.approach_surf_z:.2f} exit z={plan.exit_surf_z:.2f}")

    approach_d = float(args.approach_dist if args.approach_dist is not None else plan.approach_dist)
    exit_d = float(args.exit_dist if args.exit_dist is not None else plan.exit_dist)
    tag = f"_{args.tag}" if args.tag else ""
    written = []
    for side in (["approach", "exit"] if args.side == "both" else [args.side]):
        pin = args.approach_pin if side == "approach" else args.exit_pin
        dist = approach_d if side == "approach" else exit_d
        written.append(_emit_segment(mb, targeter, plan, family, side, pin, dist,
                                     os.path.join(args.out_dir, f"{side}{tag}.npz"), args, raw_schema,
                                     plan_path=args.plan, start=args.approach_start))

    kf_t, kf_qpos, kf_kind = mb.captured_keyframes()
    sidecar = os.path.join(args.out_dir, "_keyframes.npz")
    np.savez_compressed(sidecar, clip_idx=np.zeros(len(kf_t), np.int32), t=kf_t, qpos=kf_qpos,
                        kind=np.array(json.dumps(list(kf_kind))),
                        joint_names=np.array(json.dumps(list(mb_env.G1_JOINT_NAMES))), fps=np.array(mb.fps))
    print(f"[mb_seg] done: {len(written)} segments -> {args.out_dir} "
          f"({len(kf_t)} pinned keyframes of the last segment -> {sidecar})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
