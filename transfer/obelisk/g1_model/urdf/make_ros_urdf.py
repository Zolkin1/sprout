"""Derive the ROS package's URDF from the trained robot's URDF, instead of copying it by hand.

Run from the repo root::

    python transfer/obelisk/g1_model/urdf/make_ros_urdf.py \\
        --urdf robot_assets/g1_perceptive/g1_perceptive.urdf \\
        --out transfer/obelisk/g1_model/urdf/g1_perceptive.urdf

There are now FOUR descriptions of this robot -- the training URDF, the USD IsaacLab spawns
from it, the MJCF ``motion_gen``'s FK and MuJoCo read (generated by
``transfer/sim/robots/g1/make_g1_mjcf.py``), and this one, which is what the deploy stack
actually FKs. The first three are derived from the first. This one was not, and that is
precisely how it came to be a different robot: ``g1_model/urdf/g1_29j.urdf`` was byte-identical
across main, the deploy branch and the training-refresh branch, so while training moved to the
perceptive G1 -- mode_11 waist offsets, a 2.64 kg backpack, rubber hands -- the deploy path kept
FK'ing the old one. Nothing errored. ``torso_link`` exists in both and so do all 29 joints, so
``g1_deploy::CameraPoseFk`` resolved every name it looks up and placed both depth cameras about
10 mm high, on every unprojected xyz channel, forever. That is the same failure rtr's
``refresh_fk_channels.py`` measured offline at 10.447 mm against a 5 mm tolerance.

**Why a separate file at all, rather than pointing the controller at the training URDF.**
Pinocchio does not load meshes, so the camera FK would be happy with the source file and its
relative mesh paths. ``robot_state_publisher`` and RViz are not: they resolve ``package://``,
which the training URDF cannot use because it is not inside a ROS package. So the ROS copy
exists for the VISUAL half, and generating it is what stops the two halves describing different
robots again.

What this does, and nothing more:

* rewrites every ``filename="<anywhere>/<base>.STL"`` to ``package://g1_model/meshes/<base>.STL``
  -- mesh references are the only thing that differs between the two files;
* copies any referenced mesh the package does not already have out of the source URDF's own
  directory (for the perceptive robot that is the backpack shell and the two camera
  assemblies), so the generated URDF is never left naming a file that is not there;
* refuses if a referenced mesh is nowhere to be found, rather than emitting a URDF that
  RViz will silently draw with a piece missing.

Kinematics, inertials, joint names and joint ORDER are copied through untouched. This is a
mesh-path rewrite, not a translation, so there is no arithmetic here to be wrong.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
#: The package's mesh directory, which is what ``package://g1_model/meshes`` resolves to.
MESH_DIR = os.path.join(os.path.dirname(HERE), "meshes")

#: Matches a URDF mesh reference, capturing the basename. URDF puts the path in a `filename`
#: attribute on `<mesh>`; nothing else in the file uses that attribute name.
_MESH_RE = re.compile(r'filename="([^"]*/)?([^"/]+)"')


def find_source_mesh(base: str, urdf_path: str) -> str | None:
    """Locate a referenced mesh on disk, searching outward from the source URDF.

    Args:
        base: The mesh file's basename, e.g. ``ASSY_backpack.STL``.
        urdf_path: The source URDF, whose directory tree is searched first.

    Returns:
        An absolute path, or ``None`` when the mesh cannot be found.
    """
    root = os.path.dirname(os.path.abspath(urdf_path))
    # The source URDF's own tree first (that is where a robot-specific mesh lives), then its
    # parent, which is where the shared g1 meshes sit.
    for start in (root, os.path.dirname(root)):
        for dirpath, _dirnames, filenames in os.walk(start):
            if base in filenames:
                return os.path.join(dirpath, base)
    return None


def rewrite(urdf_path: str, out_path: str, mesh_dir: str = MESH_DIR) -> tuple[int, list[str]]:
    """Write the ROS copy of ``urdf_path``, with package-relative mesh paths.

    Args:
        urdf_path: Source URDF (the one training and the MJCF are derived from).
        out_path: Where to write the ROS copy.
        mesh_dir: The package's mesh directory to reference and to fill.

    Returns:
        ``(number of mesh references rewritten, basenames copied in)``.

    Raises:
        FileNotFoundError: If a referenced mesh is in neither the package nor the source tree.
    """
    with open(urdf_path, encoding="utf-8") as f:
        text = f.read()

    wanted: set[str] = set()

    def _sub(match: re.Match) -> str:
        base = match.group(2)
        wanted.add(base)
        return f'filename="package://g1_model/meshes/{base}"'

    out_text, count = _MESH_RE.subn(_sub, text)

    copied: list[str] = []
    missing: list[str] = []
    for base in sorted(wanted):
        if os.path.isfile(os.path.join(mesh_dir, base)):
            continue
        src = find_source_mesh(base, urdf_path)
        if src is None:
            missing.append(base)
            continue
        shutil.copy2(src, os.path.join(mesh_dir, base))
        copied.append(base)
    if missing:
        raise FileNotFoundError(
            "these meshes are referenced by " + urdf_path + " but exist neither in " +
            mesh_dir + " nor anywhere under the source URDF's tree: " + ", ".join(missing) +
            ". Emitting the URDF anyway would give RViz a robot with a piece missing and no "
            "error to explain it.")

    # The source path is echoed AS PASSED, deliberately: an os.path.relpath against the cwd
    # would make the generated file depend on where the generator was run from, and then
    # "is this file up to date with its source" is not a question anything can answer. Run it
    # from the repo root, as the docstring says, and the banner is a repo-relative path.
    banner = (
        "<!-- GENERATED by transfer/obelisk/g1_model/urdf/make_ros_urdf.py from\n"
        f"     {urdf_path}\n"
        "     Do not edit: this is the deploy stack's copy of the TRAINED robot, and editing\n"
        "     it here is how the two came to be different robots in the first place. Change\n"
        "     the source URDF and re-run the generator. -->\n")
    # After the XML declaration if there is one, so the file stays well-formed.
    if out_text.startswith("<?xml"):
        head, _, tail = out_text.partition("\n")
        out_text = head + "\n" + banner + tail
    else:
        out_text = banner + out_text

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(out_text)
    return count, copied


def main() -> None:
    """Parse arguments and write the ROS URDF."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--urdf", required=True, help="Source URDF (the trained robot's).")
    parser.add_argument("--out", required=True, help="Output URDF, inside g1_model/urdf/.")
    parser.add_argument("--mesh_dir", default=MESH_DIR,
                        help="Package mesh directory to reference and fill (default: "
                             "g1_model/meshes).")
    args = parser.parse_args()

    count, copied = rewrite(args.urdf, args.out, args.mesh_dir)
    print(f"[ok] {args.out}: {count} mesh references rewritten to package://g1_model/meshes")
    if copied:
        print(f"[ok] copied {len(copied)} mesh(es) into {args.mesh_dir}: {', '.join(copied)}")
    else:
        print(f"[ok] every referenced mesh was already in {args.mesh_dir}")


if __name__ == "__main__":
    main()
