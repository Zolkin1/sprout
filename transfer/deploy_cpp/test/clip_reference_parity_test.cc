// The clip reference path, held to the python oracle end to end: pack read, channel
// resolution by name, placement lift, and the window itself.
//
// Driven over the REAL committed pack rather than a synthetic one, so the resolver meets the
// real name lists -- 155 position channels including 13 "<body>@root" blocks whose
// quaternions are stored w,x,y,z while the base's are x,y,z,w. A synthetic pack would not
// catch a resolver that confused them.
//
// The pack is not duplicated into the fixture set: it ships with the runtime anyway, and a
// second copy is a second thing to regenerate. Fixtures carry only the robot trajectory and
// the windows python produced from it.

#include <gtest/gtest.h>

#include <sys/stat.h>

#include <cmath>
#include <string>
#include <vector>

#include "fixture.h"
#include "g1_deploy/clip_reference.h"
#include "g1_deploy/window.h"

namespace {

using g1_deploy::ClipReference;
using g1_deploy::QuatXyzw;
using g1_deploy::Vec3;
using g1_deploy::test::Case;
using g1_deploy::test::DefaultFixtureDir;
using g1_deploy::test::Fixtures;

const Fixtures& Load() {
  static const Fixtures fixtures = Fixtures::Load(DefaultFixtureDir());
  return fixtures;
}

/// Where transfer/ is, so a pack path recorded relative to it resolves.
std::string TransferRoot() { return G1_DEPLOY_TRANSFER_DIR; }

/// Whether the pack a case names is on disk.
///
/// The debug clips are GITIGNORED -- built locally from a clip library, like the .h5 they come
/// from -- so a fresh clone has the fixtures but not the pack they were generated over. That
/// has to skip with the command to build it, not throw: a hard failure there reads as a broken
/// port rather than as an artifact nobody has built yet.
bool PackPresent(const Case& c) {
  struct stat st;
  const std::string dir = TransferRoot() + "/" + c.strings.at("pack_dir");
  return ::stat((dir + "/manifest.json").c_str(), &st) == 0;
}

std::vector<g1_deploy::ReferenceBlock> Blocks(const Case& c) {
  const auto it = c.string_lists.find("blocks");
  EXPECT_NE(it, c.string_lists.end());
  std::vector<g1_deploy::ReferenceBlock> out;
  for (const std::string& name : it->second) out.push_back(g1_deploy::BlockFromName(name));
  return out;
}

}  // namespace

// Every case, or the suite silently covers nothing -- the fixtures are regenerated by a
// script that can be run with the pack absent, in which case it skips the clip cases.
TEST(ClipReferenceParity, FixturesArePresent) {
  ASSERT_FALSE(Load().ForFunction("clip_reference_window").empty())
      << "no clip_reference_window fixtures. Build the pack with "
         "transfer/deploy/tools/dump_clip_pack.py, then re-run dump_parity_fixtures.py.";
}

TEST(ClipReferenceParity, MatchesThePythonOracle) {
  for (const Case* c : Load().ForFunction("clip_reference_window")) {
    SCOPED_TRACE(c->name);
    if (!PackPresent(*c)) {
      GTEST_SKIP() << "no clip pack at " << c->strings.at("pack_dir")
                   << "; build it with: python scripts/rsl_rl/make_debug_clips.py && "
                      "python transfer/deploy/tools/dump_clip_pack.py <lib>.h5";
    }
    ClipReference::Config cfg;
    cfg.pack_dir = TransferRoot() + "/" + c->strings.at("pack_dir");
    cfg.case_name = c->strings.at("case");
    cfg.base_frame_name = c->strings.at("base_frame_name");
    cfg.joint_names = c->string_lists.at("joint_names");
    cfg.ego_anchor_every = c->ints.at("ego_anchor_every");
    // The fixture starts partway into the clip, which is the interesting case: the cadence
    // phase has to move with the start, or the latch fires on different steps than the
    // re-placement does and the window stops being a function of the clip alone.
    cfg.start_time = c->ints.at("start_step") * c->Double("dt");
    ClipReference clip = ClipReference::Load(cfg);
    ASSERT_EQ(clip.start_step(), c->ints.at("start_step"));

    const std::vector<int> offsets = c->int_lists.at("offsets");
    const auto blocks = Blocks(*c);
    const int nj = c->ints.at("num_joints");
    const int nee = c->ints.at("num_ee_frames");
    const int d = g1_deploy::WindowDim(nj, nee, blocks);
    const int ticks = c->ints.at("num_ticks");

    const auto& pos = c->In("robot_pos");
    const auto& quat = c->In("robot_quat");
    const auto& want = c->Out("window");
    const auto& want_cmd = c->Out("command_window");
    ASSERT_EQ(want.stride(), static_cast<int>(offsets.size()) * d);

    // A fixture nothing can fail is worse than no fixture: a standing stretch produces a
    // near-constant window and an all-zero command block, against which a C++ path returning
    // zeros would pass. The dumper picks a moving span; this is the check on this side.
    double want_max = 0.0, want_cmd_max = 0.0;
    for (const double v : want.data) want_max = std::max(want_max, std::abs(v));
    for (const double v : want_cmd.data) want_cmd_max = std::max(want_cmd_max, std::abs(v));
    ASSERT_GT(want_max, 0.1) << "the window fixture carries no signal";
    ASSERT_GT(want_cmd_max, 0.1) << "the command fixture carries no signal";

    std::vector<double> got(offsets.size() * d);
    std::vector<double> got_cmd;
    for (int t = 0; t < ticks; ++t) {
      const double* p = pos.row(t);
      const double* q = quat.row(t);
      clip.Serve(t, Vec3(p[0], p[1], p[2]), QuatXyzw(q[0], q[1], q[2], q[3]), offsets, nj, nee,
                 blocks, got.data(), &got_cmd);
      const double* expect = want.row(t);
      for (size_t i = 0; i < got.size(); ++i) {
        ASSERT_NEAR(got[i], expect[i], c->atol)
            << "tick " << t << " element " << i << " (node " << i / d << ", offset "
            << offsets[i / d] << ")";
      }
      const double* expect_cmd = want_cmd.row(t);
      for (size_t i = 0; i < got_cmd.size(); ++i) {
        ASSERT_NEAR(got_cmd[i], expect_cmd[i], c->atol) << "command tick " << t << " el " << i;
      }
    }
  }
}

// THE property the C++ clip path exists on: with the placement and the anchor solved from the
// robot on the same tick, the served window is a pure function of the clip. Two robots 100 m
// apart, one walking and one standing still, must be served the same numbers -- because this
// runtime has no odometry to serve anything else with.
TEST(ClipReferenceParity, TheServedWindowIsOdometryFree) {
  const auto cases = Load().ForFunction("clip_reference_window");
  ASSERT_FALSE(cases.empty());
  const Case& c = *cases.front();
  if (!PackPresent(c)) GTEST_SKIP() << "no clip pack; see MatchesThePythonOracle";
  ClipReference::Config cfg;
  cfg.pack_dir = TransferRoot() + "/" + c.strings.at("pack_dir");
  cfg.case_name = c.strings.at("case");
  cfg.base_frame_name = c.strings.at("base_frame_name");
  cfg.joint_names = c.string_lists.at("joint_names");
  cfg.ego_anchor_every = c.ints.at("ego_anchor_every");

  const std::vector<int> offsets = c.int_lists.at("offsets");
  const auto blocks = Blocks(c);
  const int nj = c.ints.at("num_joints");
  const int nee = c.ints.at("num_ee_frames");
  const int d = g1_deploy::WindowDim(nj, nee, blocks);
  const int ticks = 3 * cfg.ego_anchor_every;

  ClipReference walking = ClipReference::Load(cfg);
  ClipReference stalled = ClipReference::Load(cfg);
  std::vector<double> a(offsets.size() * d), b(offsets.size() * d);
  double worst = 0.0;
  for (int t = 0; t < ticks; ++t) {
    walking.Serve(t, Vec3(0.012 * t, -0.004 * t, 0.79),
                  QuatXyzw(0.0, 0.0, std::sin(0.004 * t), std::cos(0.004 * t)), offsets, nj, nee,
                  blocks, a.data(), nullptr);
    stalled.Serve(t, Vec3(100.0, -50.0, 0.83), QuatXyzw(0.0, 0.0, 0.0, 1.0), offsets, nj, nee,
                  blocks, b.data(), nullptr);
    for (size_t i = 0; i < a.size(); ++i) worst = std::max(worst, std::abs(a[i] - b[i]));
  }
  EXPECT_LT(worst, 1e-12) << "the served window depends on where the robot is (worst " << worst
                          << " m). A deploy runtime with no odometry cannot serve that.";
}

TEST(ClipReferenceParity, AnUnknownCaseNamesTheOnesPresent) {
  const auto cases = Load().ForFunction("clip_reference_window");
  ASSERT_FALSE(cases.empty());
  if (!PackPresent(*cases.front())) GTEST_SKIP() << "no clip pack; see MatchesThePythonOracle";
  ClipReference::Config cfg;
  cfg.pack_dir = TransferRoot() + "/" + cases.front()->strings.at("pack_dir");
  cfg.case_name = "no_such_case";
  cfg.joint_names = cases.front()->string_lists.at("joint_names");
  try {
    ClipReference::Load(cfg);
    FAIL() << "an unknown case must throw";
  } catch (const std::runtime_error& e) {
    EXPECT_NE(std::string(e.what()).find("no_such_case"), std::string::npos);
    EXPECT_NE(std::string(e.what()).find("walk_backward"), std::string::npos)
        << "the message must list what IS there: " << e.what();
  }
}

// A tracking_mode="body" tracker observes body_pos_ref / body_vel_ref, which this path does
// not serve. Refusing at load names the cause; letting it through fails much later, inside
// ObsAssembler, pointing at a term rather than at the configuration.
TEST(ClipReferenceParity, ABodyTrackingTrackerIsRefused) {
  ClipReference::Config cfg;
  cfg.pack_dir = "/nonexistent";
  cfg.case_name = "stand";
  cfg.root_frame_bodies = {"torso_link"};
  EXPECT_THROW(ClipReference::Load(cfg), std::runtime_error);
}
