"""Every MuJoCo entry point must default to the robot Isaac actually trains.

The perceptive robot changed the motors (mode_11), the hands (16 Dex3 links -> one rubber hand
per side), and added a compute backpack and two camera mounts. It did NOT change the joint
count or their order -- 29, identical -- which is exactly what makes a stale default dangerous:
a sim2sim run against ``g1_29j`` loads clean, reports plausible numbers, and is measuring a
different robot. No shape check can see it, and the pre-existing sim2sim numbers would look
like a regression in the policy rather than a swap of the model.

So this pins two things:

* every ``--robot`` / ``--robot_name`` default names the current robot; and
* a scene file exists for each of them, since a default pointing at a scene that was never
  generated fails at load with a path error that reads like a typo.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[3]
_ROBOTS = _ROOT / "transfer" / "sim" / "robots" / "g1"

#: The robot every entry point should reach for by default.
CURRENT_ROBOT = "g1_perceptive"

#: Entry points that take a robot on the command line.
_ENTRY_POINTS = [
    "scripts/rsl_rl/compare_depth_sim2sim.py",
    "scripts/rsl_rl/clip_ab_sweep.py",
    "scripts/rsl_rl/compare_sim2sim.py",
    "transfer/sim/generate_clip_tile_scene.py",
    "transfer/sim/verify_depth_cameras.py",
    "transfer/sim/generate_stairs_scene.py",
    "transfer/sim/g1_runner.py",
    "transfer/sim/gen_tracker_runner.py",
]

#: Scenes that must exist for the current robot, by suffix.
_SCENES = ["basic_scene", "terrain_scene", "tile0_scene", "tile20_scene", "tile26_scene"]

_ARG = re.compile(r'"--robot(?:_name)?"\s*,(?:\s*type=str\s*,)?\s*default="([^"]+)"')


@pytest.mark.parametrize("rel", _ENTRY_POINTS)
def test_the_robot_default_is_current(rel):
    src = (_ROOT / rel).read_text(encoding="utf-8")
    found = _ARG.findall(src)
    assert found, f"{rel} no longer declares a --robot/--robot_name default; update this list"
    for got in found:
        assert got == CURRENT_ROBOT, (
            f"{rel} defaults to {got!r}, not {CURRENT_ROBOT!r}. That robot has different "
            "motors, hands and payload but the SAME 29 joints in the same order, so the run "
            "would load clean and silently measure the wrong machine."
        )


@pytest.mark.parametrize("scene", _SCENES)
def test_the_current_robot_has_that_scene(scene):
    path = _ROBOTS / f"{CURRENT_ROBOT}_{scene}.xml"
    assert path.is_file(), (
        f"{path.name} is missing, so a default-argument run of that scene fails at load. "
        "Regenerate with generate_stairs_scene.py / generate_clip_tile_scene.py "
        f"--robot {CURRENT_ROBOT}."
    )
    assert f'include file="{CURRENT_ROBOT}.xml"' in path.read_text(encoding="utf-8"), (
        f"{path.name} does not include {CURRENT_ROBOT}.xml -- the scene is named for one "
        "robot and built around another"
    )


def test_the_current_robot_model_exists():
    """Generated by make_g1_mjcf.py from the URDF; the scenes are useless without it."""
    assert (_ROBOTS / f"{CURRENT_ROBOT}.xml").is_file()
